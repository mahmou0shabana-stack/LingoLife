/**
 * أقسامُ القالب — **معرّفاتٌ داخليّةٌ لا نصوصُ عرض**.
 *
 * ⚠️ والفصلُ مقصود: العنوانُ الذي يكتبه ChatGPT قد يتغيّر لفظُه غدًا
 *    («الإحساس» → «المعنى»)، والقرارُ الذي يبنيه المحلّلُ عليه لا
 *    يتغيّر. فالمرادفاتُ تُضاف إلى الجدول، والمنطقُ لا يُمَسّ.
 */
export const SECTION = Object.freeze({
  /** الجملةُ الأصليّةُ التي بُنيت عليها المسودّة. */
  SOURCE: 'source',
  /** شرحُ الإحساس/المعنى — نثرٌ عربيٌّ لا ترجمة. */
  SENSE: 'sense',
  /** أمثلةٌ: روسيٌّ فترجمتُه، مكرَّرًا. */
  EXAMPLES: 'examples',
  /** قالبٌ نحويّ — رمزٌ لا جملةٌ تُنطَق. */
  TEMPLATE: 'template',
  /** سؤالٌ/ملاحظةٌ نثريّة. */
  QUESTION: 'question',
  /** مقارنةٌ: صيغتان وترجمتاهما. */
  COMPARE: 'compare',
  /** إعادةُ البناء: جملةٌ جديدةٌ وترجمتُها. */
  REBUILD: 'rebuild',
  /** أسئلةُ الاسترجاع — **الاتّجاهُ معكوس**: عربيٌّ يسأل وروسيٌّ يجيب. */
  RECALL: 'recall',
  /** شريطُ الاسترجاع السريع: مفرداتٌ وترجماتُها. */
  STRIP: 'strip',
  /** خارجَ أيّ قسمٍ معروف — السلوكُ الافتراضيّ. */
  NONE: 'none',
});

/**
 * ⚠️ **جدولُ العناوين — والمرادفاتُ لأنّ اللفظَ يتغيّر والقالبُ يبقى**
 *    (بند ٣): «الإحساس» و«المعنى» و«الحسّ» كلُّها تقول الشيءَ نفسه.
 *    والبندُ ٢ صريح: مرونةٌ تكفي لفهم التغيّر الصغير، بلا هشاشة.
 */
const SECTION_WORDS = [
  [SECTION.SOURCE, ['الجملة الأساسية', 'الجملة الأصلية', 'الأصل', 'النص الأصلي', 'الجملة']],
  [SECTION.SENSE, ['الإحساس', 'الاحساس', 'المعنى', 'الحس', 'الشعور', 'الفكرة']],
  [SECTION.EXAMPLES, ['أمثلة', 'امثلة', 'مثال', 'الأمثلة', 'الامثلة']],
  [SECTION.TEMPLATE, ['القالب', 'قالب', 'النمط', 'التركيب', 'الصيغة', 'البنية']],
  [SECTION.QUESTION, ['السؤال', 'سؤال', 'ملاحظة', 'ملحوظة', 'تنبيه', 'انتبه']],
  [SECTION.COMPARE, ['مقارنة', 'المقارنة', 'الفرق', 'مقابلة']],
  [SECTION.REBUILD, ['إعادة البناء', 'اعادة البناء', 'إعادة التركيب', 'اعادة التركيب', 'التركيب من جديد']],
  [SECTION.RECALL, ['أسئلة الاسترجاع', 'اسئلة الاسترجاع', 'الاسترجاع', 'أسئلة المراجعة', 'اسئلة المراجعة', 'كيف تقول']],
  [SECTION.STRIP, ['شريط الاسترجاع السريع', 'الاسترجاع السريع', 'شريط سريع', 'مراجعة سريعة', 'شريط الاسترجاع']],
];

/**
 * يطبّع سطرًا قبل مطابقته بعنوانِ قسم.
 *
 * ⚠️ **والتسامحُ هنا هو كلُّ الفرق** (بند ٤): نقطتان أو لا نقطتان،
 *    عربيّتان (`：`) أو لاتينيّتان، مسافةٌ قبلهما أو لا، همزةٌ مكتوبةٌ
 *    أو مُهمَلة، تشكيلٌ أو تجريد، شرطةٌ زخرفيّةٌ في البداية. كلُّها
 *    تغيّراتٌ **لا تغيّر المعنى**، وكسرُ الاستيرادِ لأجلها هو بالضبط
 *    الهشاشةُ التي نهى عنها البند ٣.
 */
function normalizeLabel(line) {
  return String(line || '')
    .normalize('NFC')
    /* التشكيلُ والتطويل زينةٌ لا حرف. */
    .replace(/[ً-ٰٟـ]/g, '')
    /* زخارفُ البداية والنهاية: نجومٌ وشُرَطٌ ورموزٌ وأقواس. */
    .replace(/^[\s*_#•·—–\-«"'[(【〈]+/, '')
    .replace(/[\s*_#•·—–:：.،,)\]】〉»"']+$/, '')
    /* توحيدُ الهمزات والألف المقصورة والتاء المربوطة. */
    .replace(/[إأآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/** الجدولُ مبنيًّا مرّةً — مفتاحُه اللفظُ مُطبَّعًا. */
const LABEL_INDEX = new Map();
for (const [id, words] of SECTION_WORDS) {
  for (const word of words) LABEL_INDEX.set(normalizeLabel(word), id);
}

/**
 * هل هذا السطرُ عنوانُ قسم؟ — وأيُّ قسم؟
 *
 * ⚠️ **ويُشترط أن يكون السطرُ عنوانًا وحدَه** لا جملةً تبدأ بالكلمة:
 *    «الإحساس هنا مختلف عن غيره» ليست عنوانًا، و«الإحساس:» هي.
 *    ولذلك تُطابَق السلسلةُ **كاملةً** بعد التطبيع، لا كبادئة.
 *
 * @param {string} line
 * @returns {string|null} أحدُ قيم `SECTION` أو `null`
 */
export function matchSection(line) {
  const clean = normalizeLabel(line);
  if (!clean || clean.length > 40) return null;
  return LABEL_INDEX.get(clean) || null;
}

/**
 * هل هذا سطرُ **عنوانِ الوثيقة** — «مسودة — Core Chunks»؟
 *
 * ⚠️ **وشرطُه أن يكون في المقدّمة، قبل أيّ قسم.** بعد القياس بقي
 *    إنذارٌ كاذبٌ واحدٌ من ٢٥: عنوانُ المسودّة نفسُه، وُسم «عربيًّا بلا
 *    أصل». وهو ليس ترجمةً ضاع أصلُها — هو اسمُ الوثيقة.
 *
 * ⚠️ **ولا يُعمَّم على كلّ سطرٍ قصير.** الشرطان معًا: كلمةٌ دالّةٌ
 *    معروفة (مسودّة/draft/core chunks)، **و**موقعٌ في المقدّمة. فلا
 *    يبتلع هذا الاستثناءُ سطرًا عربيًّا حقيقيًّا في وسط الوثيقة.
 */
/*
 * ⚠️ **ولا `\b` هنا.** كتبتُها أوّلَ مرّة `مسوده\b` فلم تطابق شيئًا:
 *    `\b` في JS حدُّ كلمةٍ **لاتينيّ** (`\w` = `[A-Za-z0-9_]`)، والحرفُ
 *    العربيُّ ليس منها — فلا حدَّ بينه وبين المسافة. عطبٌ صامتٌ يجعل
 *    القاعدةَ موجودةً في الكود وغائبةً في العمل، ولم يكشفه إلّا القياس.
 */
const TITLE_WORDS = /^(مسوده|draft|core\s*chunks|قطع\s*اساسيه)(?![\p{L}])/iu;

export function looksDocTitle(line) {
  const clean = normalizeLabel(line);
  if (!clean || clean.length > 60) return false;
  if (/[.!?؟…]$/.test(String(line).trim())) return false;
  return TITLE_WORDS.test(clean);
}

