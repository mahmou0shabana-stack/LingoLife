/**
 * LingoLife — هُويّةُ الكيان والموضع في ذاكرة اللغة (WS-C، بنود ٢…٤ و٣٤)
 *
 * ═══════════════════════════════════════════════════════════════
 * الفرقُ الحاكم: الكيانُ ليس الظهور
 * ═══════════════════════════════════════════════════════════════
 *
 * **الكيان** هو الشيءُ اللغويُّ نفسُه: «согласование».
 * **الظهور** واقعةٌ: «وقع في السكريبت س، الجملة ٣، الكلمة ٧».
 *
 * وصفٌّ واحدٌ للاثنين معًا يعني أن ظهورًا جديدًا **يدهس** القديم —
 * وذلك بعينه ما يمنعه بند ٧١: «كلمةٌ تقابلها غدًا لا تحلّ محلّ كلمةٍ
 * قابلتَها أمس».
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ والتطبيعُ لا يمسّ ما رأيتَه
 * ═══════════════════════════════════════════════════════════════
 *
 * لكلّ موضعٍ **صورتان**: `surface` كما كُتبت بحرفها الكبير وعلامتها
 * وترقيمها، و`canonical` مفتاحُ البحث. والأولى لا تُشتقّ من الثانية
 * أبدًا — وإلّا صار «Докуме́нт» يُعرَض «документ» وضاع ما رأيتَه (بند ٤).
 *
 * ⚠️ **ولا اشتقاقَ صرفيّ**: «заполнен» و«заполнена» **كيانان**، ولا
 *    يُدمجان لأنهما «يبدوان متشابهين». ولا محلّلَ صرفيًّا روسيًّا في
 *    التطبيق — و`UNBUILT.words` في `language-service.js` تقول ذلك منذ
 *    WS5. واختراعُ الدمج هنا كذبٌ لغويّ (بندا ٤ و٦٨).
 */

import { normalize } from '../../utils/normalization.js';

/** أنواعُ الكيان — ثلاثةٌ لا واحد (بند ٣). */
export const ENTITY_KIND = Object.freeze({
  WORD: 'word',
  PHRASE: 'phrase',
  SENTENCE: 'sentence',
});

/** مصادرُ الظهور — بمصطلحات المستودع القائمة (بند ٥). */
export const SOURCE_KIND = Object.freeze({
  SCRIPT: 'script',
  DRAFT: 'draft',
  CONVERSATION: 'conversation',
  EXTERNAL: 'external',
  MANUAL: 'manual',
  IMPORT: 'import',
});

/** مِن أين جاءت هذه المعلومة — يُسجَّل ولا يُعرَض دائمًا (بند ٤٧). */
export const ORIGIN = Object.freeze({
  /** لاحظه التطبيقُ في بياناتك. */
  OBSERVED: 'observed',
  /** كتبتَه بيدك. */
  USER: 'user',
  /** حُسِب من غيره. */
  DERIVED: 'derived',
  /** جاء من تحليلٍ خارجيّ — لا يملك واقعةً أبدًا (بند ١٧). */
  AI_IMPORT: 'ai_import',
  /** بياناتٌ قديمةٌ لا نعرف مصدرَها بدقّة. */
  LEGACY: 'legacy',
});

/**
 * الصورةُ المِفتاحيّة — **للبحث لا للعرض**.
 *
 * تُوحِّد: الحرفَ الكبير، وعلامةَ النبر، والترقيم، و«ё»/«е».
 * ولا تُوحِّد: الصرفَ ولا المعنى.
 */
export function canonical(text) {
  return normalize(text || '');
}

/**
 * هل هذا نصٌّ صالحٌ ليصير كيانًا مُتتبَّعًا؟
 *
 * ⚠️ **وهذه هي سياسةُ بند ٣ بحرفها**: لا يُشتقّ كلُّ ثنائيٍّ وثلاثيٍّ
 *    ممكنٍ من كلّ جملة — تلك بياناتٌ بلا معنًى تملأ القرص. الكياناتُ
 *    تُخلَق بإشارةٍ صريحة: حفظتَها، أو تدرّبتَ عليها، أو حدّدتَ مقطعًا
 *    بإصبعك، أو هي جملةُ مصدرٍ حقيقيّة.
 *
 *    أمّا **الفهرس** (`memoryOccurrences`) فيُبنى لكلّ كلمةٍ في كلّ
 *    جملةٍ — وذلك لا يُنشئ كيانًا، بل يجعل السؤالَ عن كيانٍ قائمٍ
 *    رخيصًا. والفرقُ بينهما هو الفرقُ بين «فهرسُ كتابٍ» و«كلُّ كلمةٍ
 *    فيه صارت مدخلًا في قاموسك».
 */
export function trackable(text, kind = ENTITY_KIND.WORD) {
  const key = canonical(text);
  if (!key) return false;
  if (kind === ENTITY_KIND.WORD) return !key.includes(' ');
  return true;
}

/**
 * مفتاحُ المصدر — يجمع نوعَه ومعرِّفَه في سلسلةٍ واحدةٍ قابلةٍ للفهرسة.
 *
 * ⚠️ **ومصدران مختلفان لا يلتقيان وإن تطابق نصُّهما** (بند ٣٤): جملةٌ
 *    واحدةٌ في سكريبتين هي **ظهوران** في مصدرين، لا ظهورٌ واحد.
 */
export function sourceKey(kind, id) {
  return `${kind}:${id ?? ''}`;
}

/**
 * هُويّةُ الموضع — بصمةٌ حتميّةٌ تجعل إعادةَ الفهرسة **لا تُضاعف**.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ وهذا هو جوابُ بندي ٨ و٣٤ معًا
 * ═══════════════════════════════════════════════════════════════
 *
 * · «очень очень» في جملةٍ واحدة = **موضعان** (رقما الكلمة يفترقان).
 * · فتحُ نفس الجملة غدًا = **نفسُ الموضع** (البصمةُ نفسُها)، فلا
 *   يُخلَق صفٌّ ثانٍ ولا يرتفع عدّاد.
 * · نفسُ الجملة في سكريبتين = **موضعان** (`sourceKey` يفترق).
 *
 * والبصمةُ **معرِّفُ الصفّ نفسُه** لا حقلٌ بجانبه: فالكتابةُ `put`
 * تستبدل ولا تُضيف، وهي حتميّةُ التكرار بحكم المخزن لا بحكم شرطٍ
 * نتذكّره.
 */
export function occurrenceId({
  canonical: key, sourceKey: src, unitKey = '', sentenceIndex, wordIndex,
}) {
  /*
   * ⚠️ **و«الوحدة» بُعدٌ رابعٌ للمحادثات — والفراغُ يُبقي القديمَ كما هو.**
   *
   *    المحادثةُ **مصدرٌ واحد** فيه أجزاء (بند ٤٥): كلمتان في جزأين
   *    مختلفين موضعان، والمصدرُ واحدٌ لا اثنان. ولو رقّمنا الجملَ
   *    متتابعةً عبر الأجزاء لصار تعديلُ الجزء الأوّل يزيح أرقامَ ما
   *    بعده — فتنتقل ملاحظتُك إلى كلمةٍ أخرى، وهو بعينه ما يمنعه
   *    بند ٥٤: «لا تُنسَب الملاحظةُ إلى موضعٍ آخر».
   *
   *    فمعرِّفُ الجزء داخلَ البصمة: تعديلُ جزءٍ لا يمسّ بصماتِ غيره.
   *
   * ⚠️ **والسكريبتُ والمسودّةُ بلا وحدةٍ فتبقى بصماتُهما حرفيًّا كما
   *    كانت** — فلا يتيتّم شيءٌ فُهرِس قبل اليوم.
   */
  const unit = unitKey ? `${unitKey}_` : '';
  return `MOC_${src}_${unit}${sentenceIndex}_${wordIndex}_${key}`;
}

/**
 * بصمةُ نمط الخطأ — أساسُ التكرار (بند ١٢).
 *
 * ⚠️ **حتميّةٌ ومحافِظة**: تُبنى من الصورتين معًا بعد التطبيع. فغلطتان
 *    بنفس الخطأ ونفس التصحيح تُجمَعان؛ وغلطتان مختلفتان لا تُجمَعان
 *    **مهما تشابهت حروفُهما**. ولا مسافةَ تحريرٍ هنا ولا تقاربَ نصّيّ:
 *    «لا تُدمَج غلطتان لمجرّد أن سلسلتيهما تبدوان متشابهتين» بحرفه.
 */
export function patternKey(wrong, correct) {
  const a = canonical(wrong);
  const b = canonical(correct);
  if (!a || !b) return '';
  return `${a}→${b}`;
}

/**
 * يستخرج مواضعَ الكلمات في جملةٍ — بترتيبها وبصورتها كما كُتبت.
 *
 * @param {string} sentence
 * @param {(s: string) => {display: string, spoken: string, index: number}[]} split
 *        مقسِّمُ الكلمات — يُمرَّر حقنًا فلا تعرف هذه الطبقةُ الظلَّ.
 */
export function wordPositions(sentence, split) {
  return split(sentence || '')
    .map((word) => ({
      wordIndex: word.index,
      surface: word.display,
      canonical: canonical(word.spoken),
    }))
    .filter((one) => one.canonical);
}
