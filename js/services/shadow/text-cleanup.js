/**
 * LingoLife — تنظيف النصّ المستخرَج قبل التقسيم (WS40، بند 9)
 *
 * OCR وأنواعُ الاستخراج الآلي تُخرِج أحيانًا ضوضاءً لا علاقة لها
 * باللغة: أرقامَ صفحاتٍ منفردة، خطوطًا فاصلة، رموزًا زخرفيّةً معزولة.
 * هذه الضوضاء تُفسد التقسيم لجملٍ لاحقًا — سطرٌ مثل «12» يصير «جملة»
 * بلا معنى.
 *
 * ⚠️ **والتمييز بين الترقيم الحقيقي والضوضاء هو السطر لا الحرف.**
 *    سطرٌ **بأكمله** أرقامًا أو رموزًا زخرفيّة = ضوضاء؛ رقمٌ أو علامةُ
 *    ترقيمٍ **داخل** جملةٍ روسيّة حقيقية لا تُمَسّ أبدًا — فجملةٌ روسيّة
 *    تحوي حرفًا كيريليًّا واحدًا على الأقل لا يمكن أن تطابق هذا النمط.
 *    وحيث الشكّ قائمٌ لا تُحذَف: النصُّ يبقى بعدها في صندوقٍ تراجعه
 *    أنت قبل أن يصير مقاطعَ تدريب — تنظيفٌ يُخفّف عملَ المراجعة، لا
 *    يُلغيها.
 */

/**
 * سطرٌ بأكمله أرقامٌ (page number) أو رموزٌ زخرفيّة/فاصلة (`***`،
 * `---`، `___`، `•••`) أو رمزٌ معزولٌ واحد (`+`، `=` وحدها في سطر) —
 * لا حرف كيريليّ أو لاتينيّ فيه على الإطلاق.
 */
const NOISE_LINE = /^\s*[-*_=~•·.+|^\d\s]+\s*$/;

/** يحذف أسطر الضوضاء المعزولة، ويطوي الفراغات الزائدة — لا أكثر. */
export function cleanExtractedText(raw) {
  const text = String(raw || '');
  const lines = text
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, ''))
    .filter((line) => line.trim() === '' || !NOISE_LINE.test(line));

  return lines
    .join('\n')
    // ثلاثة أسطر فارغة فأكثر تصير اثنين — فقرةٌ واحدة تبقى فقرة.
    .replace(/\n{3,}/g, '\n\n')
    .trim();
}
