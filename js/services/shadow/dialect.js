/**
 * LingoLife — تحويل العربية الفصحى إلى المصرية
 *
 * منقول حرفيًا من `_egypt()` في التطبيق القديم. تحويل معجمي بسيط،
 * لا يفهم النحو ولا السياق — لكنه يعمل جيدًا على جُمل الترجمة القصيرة
 * وهو ما كان يستخدمه التطبيق القديم بالضبط.
 *
 * ⚠️ ليس مترجمًا. يأخذ ترجمة عربية **موجودة عندك** ويقرّبها من لهجتك.
 *    لا يخترع ترجمة لنصّ غير مترجَم.
 */

/** أزواج (فصحى → مصري) بترتيب التطبيق القديم. */
const PAIRS = [
  [/كيف/g, 'إزيك'],
  [/ماذا/g, 'إيه'],
  [/لماذا/g, 'ليه'],
  [/أين/g, 'فين'],
  [/هذا/g, 'ده'],
  [/هذه/g, 'دي'],
  [/الآن/g, 'دلوقتي'],
  [/جيد/g, 'كويس'],
  [/نعم/g, 'أيوه'],
  [/\bلا\b/g, 'لأ'],
  [/يريد/g, 'عايز'],
  [/منزل/g, 'بيت'],
  [/كثيراً/g, 'أوي'],
  [/كثيرًا/g, 'أوي'],
  [/أيضاً/g, 'برضو'],
  [/أيضًا/g, 'برضو'],
];

/**
 * يحوّل نصًّا عربيًا فصيحًا إلى أقرب صيغة مصرية.
 * @param {string} text
 * @returns {string}
 */
export function toEgyptian(text) {
  if (!text) return '';
  return PAIRS.reduce((out, [pattern, replacement]) => out.replace(pattern, replacement), text);
}
