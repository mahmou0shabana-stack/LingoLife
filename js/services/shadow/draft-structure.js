/**
 * قواعدُ القراءة داخل كلّ قسم — **جدولٌ لا سلسلةُ `if`**.
 *
 * · `pairs`   — يُتوقَّع فيه روسيٌّ وترجمتُه.
 * · `prose`   — العربيُّ فيه **شرحٌ** لا ترجمةٌ ناقصة (بند ٥).
 * · `symbol`  — المحتوى رمزٌ نحويٌّ لا جملةٌ تُنطَق.
 * · `reverse` — العربيُّ يسأل والروسيُّ يجيب (بند ٣٤).
 */
export const SECTION_RULE = Object.freeze({
  [SECTION.SOURCE]: { pairs: true },
  [SECTION.SENSE]: { prose: true },
  [SECTION.QUESTION]: { prose: true },
  [SECTION.TEMPLATE]: { symbol: true },
  [SECTION.EXAMPLES]: { pairs: true },
  [SECTION.COMPARE]: { pairs: true },
  [SECTION.REBUILD]: { pairs: true },
  [SECTION.STRIP]: { pairs: true },
  [SECTION.RECALL]: { reverse: true },
  [SECTION.NONE]: { pairs: true },
});

/** قاعدةُ قسمٍ بأمان — القسمُ المجهولُ يُقرأ كالافتراضيّ. */
export const ruleOf = (section) => SECTION_RULE[section] || SECTION_RULE[SECTION.NONE];

