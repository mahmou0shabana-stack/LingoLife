/**
 * LingoLife — ناقلُ الصوت: مَن يتكلّم الآن (WS29)
 *
 * ═══════════════════════════════════════════════════════════════
 * بلاغُك
 * ═══════════════════════════════════════════════════════════════
 *
 * > «لو جيت شغّلت فويس في صفحة الشادوينج ونقلت لتاب تانية الفويس
 * >  هيفضل شغّال ومش هلاقي زرار خارجي يخليني أقفله، وهكذا.»
 *
 * و«وهكذا» هي بيتُ القصيد: **ليست حالةً واحدة بل عائلةٌ منها**. في
 * صفحة الظلّ أربعةُ أشياءَ تُصدر صوتًا:
 *
 *   ١. نطقُ الجلسة (`playback-controller`)
 *   ٢. نطقُ نصٍّ خارجيّ (نفسُ المحرّك، نسخةٌ ثانية)
 *   ٣. تسجيلاتُ الذكرى (منبعُ «أصوات» في الورقة)
 *   ٤. نطقُ كلمةٍ بضغطةٍ واحدة
 *
 * وكانت كلُّ واحدةٍ تبدأ بلا أن تسأل عن الأخرى. فحاولتُ الإصلاحَ
 * بالمقابلة: «التشغيل يُسكِت التسجيل» و«التسجيل يوقف النطق». وهي
 * **أربعةٌ في ثلاثة = اثنتا عشرة مقابلة**، ولا يُكتَب منها إلّا ما
 * يخطر ببالك.
 *
 * ⚠️ **وقِستُ ما لم يخطر**: تقلّب من تبويب «أصوات» إلى «صور» فيبقى
 *    التسجيلُ شغّالًا — وزرُّه اختفى مع التبويب. تغيّر الوضعَ فيبقى
 *    شغّالًا. أي: كلُّ بابٍ نسيتُه ثقب.
 *
 * ═══════════════════════════════════════════════════════════════
 * فالقاعدةُ صارت واحدة: **مالكٌ واحدٌ للصوت**
 * ═══════════════════════════════════════════════════════════════
 *
 * مَن يريد أن يُصدر صوتًا **يطالب** بالناقل، والمطالبةُ تُسكِت مَن
 * قبله — أيًّا كان ومن أيّ باب. فلا مقابلاتٍ تُكتَب، ولا بابَ
 * يُنسى: البابُ الجديد لا يعمل أصلًا حتى يطالب.
 *
 * ⚠️ **ولا يعرف الناقلُ كيف يُسكِت أحدًا.** كلُّ مالكٍ يعطي دالّةَ
 *    إسكاتِ نفسِه حين يطالب. فالناقلُ لا يستورد شيئًا ولا يعرف
 *    مُشغّلًا من تسجيل — ولذلك يبقى صغيرًا ومُختبَرًا.
 */

/** المالكُ الحاليّ: `{ id, silence }` — أو `null`. */
let owner = null;

/** مستمعو التغيّر — لتحديث الأزرار في الشاشة. */
const watchers = new Set();

function announce() {
  for (const fn of watchers) {
    try {
      fn(owner?.id || null);
    } catch {
      /* مستمعٌ يرمي لا يمنع البقيّة */
    }
  }
}

/**
 * يطالب بالصوت لنفسه — ويُسكِت مَن كان قبله.
 *
 * @param {string} id      اسمُ المالك (`session` · `scratch` · `voice:MED_…` · `word`)
 * @param {() => void} silence كيف يُسكِت نفسَه حين يأتي غيرُه.
 */
export function claimAudio(id, silence) {
  if (owner && owner.id !== id) {
    try {
      owner.silence();
    } catch {
      /* ⚠️ مالكٌ يرمي عند الإسكات لا يمنع الجديدَ من العمل: وإلّا
         صار عطلٌ في القديم عطلًا دائمًا في كلّ ما بعده. */
    }
  }
  owner = { id, silence };
  announce();
}

/**
 * يُسكِت كلَّ شيء.
 *
 * @param {string} [only] إن مُرِّر، لا يُسكِت إلّا إن كان هو المالك —
 *        فمَن انتهى بنفسه لا يُسكِت مَن جاء بعده.
 */
export function releaseAudio(only) {
  if (!owner) return;
  if (only && owner.id !== only) return;
  try {
    owner.silence();
  } catch {
    /* كما أعلاه */
  }
  owner = null;
  announce();
}

/** مَن يتكلّم الآن — أو `null`. */
export function audioOwner() {
  return owner?.id || null;
}

/** هل هذا هو المالك؟ */
export function ownsAudio(id) {
  return owner?.id === id;
}

/** يراقب تبدّل المالك — يعيد دالّةَ إلغاء. */
export function watchAudio(fn) {
  watchers.add(fn);
  return () => watchers.delete(fn);
}

/**
 * ⚠️ للاختبارات وحدها: يُنسي الناقلَ مالكَه **بلا إسكاته**.
 *
 * لا يُستعمَل في التطبيق: نسيانُ مالكٍ يتكلّم يترك صوتًا بلا زرّ —
 * وهو العطلُ الذي وُجد هذا الملفّ لأجله.
 */
export function forgetAudioOwner() {
  owner = null;
  announce();
}
