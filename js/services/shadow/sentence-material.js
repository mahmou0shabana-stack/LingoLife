/**
 * LingoLife — ما اشتُقّ من الجملة (WS-SC1 · بنود ٥ و٦ و٣٣ و٦١ و٦٢)
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **الجملةُ هي الأصل، وما اشتُقّ منها يسكن حولها**
 * ═══════════════════════════════════════════════════════════════
 *
 * كان السؤال «هل لهذه الجملة مسودّة؟» يُجاب بنصِّها مُطبَّعًا وحدَه.
 * فجملتان متطابقتان تتشاركان الجواب، وتعديلُ فاصلةٍ يبدّله.
 *
 * وهنا يُجاب بـ**معرّف الجملة** (`sentence-identity.js`)، والعلاقةُ
 * تُكتَب في `relationships` — نفسِ المخزن الذي يحمل كلَّ علاقات
 * التطبيق. فلا مخزنَ جديدٌ ولا فهرسٌ جديد (بند ٣٣).
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **والقديمُ يعمل كما كان** (بندا ٥ و٦)
 * ═══════════════════════════════════════════════════════════════
 *
 * مسودّاتُك القائمةُ لا تحمل معرّفَ جملة — وليس فيها ما يُصلَح. فترتيبُ
 * البحث ثلاثُ درجاتٍ صريحة:
 *
 *   ١) **ارتباطٌ ثابتٌ** بمعرّف الجملة — الجوابُ القاطع.
 *   ٢) **رجوعٌ إلى النصّ المُطبَّع** — للمسودّات التي سبقت هذا النظام.
 *   ٣) **وعند الالتباس: لا جواب.** جملتان متطابقتان في النصّ نفسِه
 *      ولمسودّةٍ قديمةٍ واحدةٍ — أيُّهما صاحبتُها؟ لا أحدَ يعرف، بما
 *      فيهم التطبيق. فيُقال «تحتاج مراجعة» ولا تُنسَب لواحدةٍ بالحظّ.
 *
 * ⚠️ **وهذه الدرجةُ الثالثةُ هي البند ٧ من قواعد المنتج حرفيًّا**:
 *    «Never guess when duplicate sentence text makes legacy attachment
 *    ambiguous». وتخمينٌ هنا يعني أن تفتح مسودّةَ جملةٍ أخرى وتظنّها
 *    مسودّتَك، فتكتب فيها.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **ولا استعلامَ لكلّ جملة** (بندا ٦١ و٦٢)
 * ═══════════════════════════════════════════════════════════════
 *
 * نصٌّ فيه أربعمئة جملةٍ يعني أربعمئة استعلامٍ لو سُئل عن كلٍّ على
 * حدة — وهو عطبُ N+1 بعينه على IndexedDB. فالخريطةُ تُبنى **مرّةً
 * للسكريبت كلِّه**: قراءةٌ واحدةٌ لمسودّات المشهد بفهرس، وقراءةٌ
 * واحدةٌ للعلاقات بفهرس `to_kind`، ثمّ مطابقةٌ في الذاكرة.
 */

import { relationships, studyDrafts } from '../../db/repositories.js';
import { STATE } from '../../db/schema.js';
import { subjectKey, SUBJECT } from '../study-draft.js';
import { sentencesOf } from './sentence-identity.js';

/**
 * نوعُ العلاقة: جملةٌ أصليّة ← مادّةٌ مشتقّة.
 *
 * ⚠️ **والاتّجاه `from` = الجملة** التزامًا باصطلاح `link-service`:
 *    الحاوي/الأصلُ `fromId` والتابعُ `toId` دائمًا. فسؤالُ «ما اشتُقّ
 *    من هذه الجملة؟» استعلامُ فهرسٍ واحد.
 */
export const SENTENCE_DRAFT = 'sentence:draft';

/** حالةُ الارتباط — تُقرأ في الشاشة ولا تُخمَّن. */
export const ATTACH = Object.freeze({
  /** ارتباطٌ ثابتٌ بمعرّف الجملة. */
  STABLE: 'stable',
  /** مسودّةٌ قديمةٌ وُجدت بالنصّ المُطبَّع، ووحيدةٌ فلا لبس. */
  LEGACY: 'legacy',
  /** نصٌّ مكرَّرٌ ومسودّةٌ قديمة — لا يُنسَب بالحظّ (بند ٥). */
  AMBIGUOUS: 'ambiguous',
});

/**
 * خريطةُ ما اشتُقّ من جملِ سجلٍّ واحد — **باستعلامَين لا بأربعمئة**.
 *
 * @param {object} record سجلُّ السكريبت/العقدة
 * @param {{sceneId?: string}} where
 * @returns {Promise<Map<number, {draft: object|null, how: string}>>}
 *          المفتاحُ **رقمُ الجملة المعروض** لأنّه ما تملكه الشاشة عند
 *          الرسم؛ والقيمةُ تحمل المسودّةَ وكيف وُجدت.
 */
export async function materialMap(record, { sceneId = null } = {}) {
  const rows = sentencesOf(record);
  const out = new Map();
  if (!rows.length) return out;

  /* ---------- (١) الارتباطاتُ الثابتة — استعلامٌ واحد ---------- */
  const ids = rows.map((one) => one.id).filter(Boolean);
  const stable = new Map();
  if (ids.length) {
    /*
     * ⚠️ **بفهرس `from_kind` لكلّ معرّف** — وهي قراءاتٌ بعددِ الجملِ
     *    **الموسومةِ وحدَها** لا بعدد الجمل كلِّها. ونصٌّ لم يُربَط به
     *    شيءٌ قطُّ لا يقرأ سطرًا واحدًا هنا.
     */
    const found = await Promise.all(
      ids.map((id) => relationships.byIndex('from_kind', [id, SENTENCE_DRAFT])),
    );
    found.flat().forEach((rel) => {
      if (rel?.state === STATE.TRASHED) return;
      stable.set(rel.fromId, rel.toId);
    });
  }

  /** المسودّاتُ التي حُسم أمرُها داخل هذا السجلّ — راجع أسفلَه. */
  const claimed = new Set(stable.values());

  /* ---------- (٢) الرجوعُ القديم — قراءةٌ واحدةٌ لا واحدةٌ لكلّ جملة ---------- */
  let legacyByKey = null;
  const needLegacy = rows.some((one) => !one.id || !stable.has(one.id));
  if (needLegacy) {
    /*
     * ═══════════════════════════════════════════════════════════
     * ⚠️ **قراءةٌ واحدةٌ بفهرس `subjectKind` — لا بالمشهد ولا بالجملة**
     * ═══════════════════════════════════════════════════════════
     *
     * أوّلُ صياغةٍ قصرت البحثَ على مسودّات المشهد (`byIndex('sceneId')`)
     * فبدَت أرخص. وكانت **خاطئةً في الاتّجاهين**:
     *
     *   · `sceneId` على المسودّة **سياقُ ميلادٍ لا مِلكيّة** — مكتوبٌ
     *     هكذا في رأس `study-draft.js`. ومسودّةٌ وُلدت في ذكرًى وفُتحت
     *     جملتُها في أخرى تُفقَد بهذا القيد. وكشفه الاختبارُ ٢٥: مسودّةٌ
     *     موجودةٌ فعلًا عادت `undefined`.
     *   · والبديلُ الآخرُ — استعلامٌ لكلّ جملة — هو عطبُ N+1 الذي يمنعه
     *     البندُ ٦١.
     *
     * فالقراءةُ **واحدةٌ** لكلّ مسودّات الجمل. وهي بياناتٌ كتبتَها بيدك:
     * مئاتٌ في أسوأ الأحوال لا ملايين. والكلفةُ `O(جمل + مسودّات)` لا
     * `O(جمل × مسودّات)` — وهو نصُّ البند ٦٢ حرفيًّا.
     */
    const all = await studyDrafts.byIndex('subjectKind', SUBJECT.SENTENCE);
    legacyByKey = new Map();
    all.filter((d) => {
      if (d.state !== STATE.ACTIVE) return false;
      /*
       * ⚠️ **والرجوعُ القديم لا يعبر حدَّ الذكرى** (بند ٣).
       *
       *    أوّلُ صياغةٍ قبلت أيَّ مسودّةٍ يطابق نصُّها — فأظهر الاختبارُ
       *    ٢٠ نصًّا جديدًا تمامًا وعليه شارةٌ: مسودّةٌ كتبتَها عن جملةٍ
       *    مشابهةٍ في ذكرًى أخرى. وذلك بعينه ما يمنعه البندُ ٣:
       *    «Do not show generic: Draft available somewhere in this text».
       *
       *    فالشرطُ: مسودّةٌ **وُلدت في هذه الذكرى**، أو لا تعرف أين
       *    وُلدت (`sceneId` فارغ) فتُقبَل لأنّها من زمنٍ لم يكن يُسجَّل.
       *
       * ⚠️ **و`sceneId` هنا مُرشِّحٌ لا هُويّة** — لا يزال «وُلدت هنا»
       *    لا «تعيش هنا». والهُويّةُ معرّفُ الجملة وحدَه.
       */
      if (d.sceneId && sceneId && d.sceneId !== sceneId) return false;
      /*
       * ═══════════════════════════════════════════════════════════
       * ⚠️ **ومسودّةٌ لها صاحبةٌ معروفةٌ لا تُعرَض على غيرها**
       * ═══════════════════════════════════════════════════════════
       *
       * كشفتها الدورةُ الحيّة: نصٌّ فيه «Хорошо́.» مرّتين، رُبطت
       * مسودّةٌ بالثانية **ربطًا ثابتًا**، فظهرت على الأولى شارةُ
       * «محتاجة مراجعة» — ونقرُها كان يفتح مسودّةَ الثانية.
       *
       * والعطبُ في الترتيب: الرجوعُ القديمُ كان يبحث بالنصّ في كلّ
       * المسودّات، بما فيها التي **حُسم أمرُها**. والالتباسُ (بند ٥)
       * حالةُ **جهلٍ حقيقيّ** — لا حالةَ تجاهُلِ ما نعرفه. فمسودّةٌ
       * سُمِّيت صاحبتُها ليست ملتبسةً على أحد.
       *
       * ⚠️ **والاستبعادُ بالمُطالَبات داخل هذا السجلّ وحدَه**: مسودّةٌ
       *    مرتبطةٌ بجملةٍ في نصٍّ آخرَ تبقى مرشَّحةً هنا — فحدُّنا هو
       *    ما نعرفه، لا ما نتمنّاه.
       */
      if (claimed.has(d.id)) return false;
      return true;
    }).forEach((d) => {
      if (!legacyByKey.has(d.subject)) legacyByKey.set(d.subject, []);
      legacyByKey.get(d.subject).push(d);
    });
  }

  /* ⚠️ عدُّ تكرار النصّ داخل السجلّ — أساسُ حكم الالتباس. */
  const seen = new Map();
  rows.forEach((one) => {
    const k = subjectKey(one.text);
    seen.set(k, (seen.get(k) || 0) + 1);
  });

  /* ---------- (٣) الجمعُ بالترتيب المُعلَن ---------- */
  const wanted = new Set();
  rows.forEach((one) => {
    if (one.id && stable.has(one.id)) wanted.add(stable.get(one.id));
  });
  const stableDrafts = wanted.size
    ? (await studyDrafts.getMany([...wanted])).filter(Boolean)
    : [];
  const byId = new Map(stableDrafts.map((d) => [d.id, d]));

  rows.forEach((one) => {
    if (one.id && stable.has(one.id)) {
      const draft = byId.get(stable.get(one.id));
      /* ⚠️ رابطٌ إلى مسودّةٍ حُذفت لا يُعرَض شارةً كاذبة (بند ٤٧). */
      if (draft && draft.state === STATE.ACTIVE) {
        out.set(one.index, { draft, how: ATTACH.STABLE });
      }
      return;
    }
    if (!legacyByKey) return;
    const key = subjectKey(one.text);
    const hits = legacyByKey.get(key) || [];
    if (!hits.length) return;
    /*
     * ⚠️ **الالتباسُ يُعلَن ولا يُحَلّ بالحظّ** (بند ٥): نصٌّ يتكرّر في
     *    السجلّ، ومسودّةٌ قديمةٌ لا تعرف أيَّ تكرارٍ تخصّ.
     */
    if (seen.get(key) > 1) {
      out.set(one.index, { draft: hits[0], how: ATTACH.AMBIGUOUS });
      return;
    }
    out.set(one.index, { draft: hits[0], how: ATTACH.LEGACY });
  });

  return out;
}

/**
 * يوائم مقاطعَ جلسةِ ظلٍّ بجملِ مصدرها.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **ورقمُ المقطع ليس رقمَ الجملة** — وهذا ليس تفصيلًا
 * ═══════════════════════════════════════════════════════════════
 *
 * `createSession` تقبل `segments` جاهزةً حين تختار أنت جملًا بعينها،
 * فتصير الجلسةُ **جزءًا** من النصّ لا صورتَه. فالمقطعُ الثالثُ في
 * الجلسة قد يكون الجملةَ التاسعةَ في السكريبت.
 *
 * فالمواءمةُ **مشيٌ بالترتيب**: نمرّ على المقاطع وعلى جملِ المصدر معًا،
 * وكلَّما تطابق نصّان أخذنا المعرّفَ وتقدّمنا. وهذا يعطي:
 *
 *   · الجلسةَ الكاملةَ مطابقةً تامّةً واحدةً بواحدة.
 *   · والجلسةَ الجزئيّةَ مطابقةً صحيحةً ما دام ترتيبُها ترتيبَ المصدر.
 *   · **والمتكرّرَ صحيحًا** — لأنّ المشيَ لا يعود للوراء، فالتكرارُ
 *     الأوّلُ يأخذ الأوّلَ والثاني الثاني.
 *
 * ⚠️ **وما لم يُطابَق يعود `null`** ولا يُخمَّن: مقطعٌ حُرِّر نصُّه بعد
 *    بناء الجلسة لا هُويّةَ له، ويعمل عندها الرجوعُ القديم.
 *
 * @param {object} record سجلُّ المصدر
 * @param {string[]} segmentTexts نصوصُ المقاطع بترتيبها
 * @returns {(string|null)[]} معرّفُ الجملة لكلّ مقطع
 */
export function alignSegments(record, segmentTexts) {
  const rows = sentencesOf(record);
  return alignSegmentRows(record, segmentTexts).map((at) => (at < 0 ? null : rows[at].id));
}

/**
 * نفسُ المواءمةِ، لكن تُرجع **رقمَ الجملة في المصدر** لا معرّفَها.
 *
 * ⚠️ **ولمَ اثنتان؟** لأنّ القراءةَ تحتاج المعرّفَ (لتسأل العلاقات)،
 *    والكتابةَ تحتاج الرقمَ (لأنّ المعرّفَ **لم يُولَد بعد**: سجلٌّ لم
 *    يُربَط به شيءٌ قطُّ لا يحمل معرّفاتٍ أصلًا — بند ٦). فلو كانت
 *    الكتابةُ تسأل عن المعرّف لَعادت `null` دائمًا في أوّل ربطٍ على
 *    الإطلاق، وهو بالضبط الحالةُ التي وُجدت من أجلها.
 *
 * @returns {number[]} رقمُ الجملة لكلّ مقطع، أو `-1` إن لم تُطابَق.
 */
export function alignSegmentRows(record, segmentTexts) {
  const rows = sentencesOf(record).map((one) => subjectKey(one.text));
  const keys = segmentTexts.map((t) => subjectKey(t));

  /* المشيُ من الأوّل: أوّلُ تطابقٍ متاحٍ يفوز. */
  const left = new Array(keys.length).fill(-1);
  let at = 0;
  keys.forEach((key, i) => {
    if (!key) return;
    for (let j = at; j < rows.length; j += 1) {
      if (rows[j] === key) { left[i] = j; at = j + 1; return; }
    }
  });

  /*
   * ═══════════════════════════════════════════════════════════════
   * ⚠️ **والمشيُ من الآخر — لأنّ مشيًا واحدًا كان يُخمِّن بلا أن يقول**
   * ═══════════════════════════════════════════════════════════════
   *
   * أمسكه الاختبارُ ٢: نصٌّ فيه «Хорошо.» في الجملتين ٢ و٤، وجلسةٌ
   * جزئيّةٌ من الجملتين ٤ و٥. والمشيُ من الأوّل يبدأ من الصفر فيلقى
   * «Хорошо.» في الجملة ٢ ويأخذها — فتُربَط مذاكرتُك بجملةٍ لم تفتحها.
   *
   * والحقيقةُ أنّ الترتيبَ وحدَه **لا يكفي للحسم** هنا: `[١،٤]` و
   * `[٣،٤]` كلاهما يحفظ الترتيب، فأيُّهما جلستُك؟ لا يُعرَف من النصّ.
   *
   * فيُمشى مرّتين: من الأوّل ومن الآخر. وما اتّفق عليه المشيان فهو
   * الوحيدُ الممكن — وما اختلفا فيه فللسؤال أكثرُ من جواب، فيعود
   * `-1` ولا يُختار أحدُهما بالحظّ. وهو البندُ ٧ حرفيًّا.
   *
   * ⚠️ **وثمنُ الصمت أرخصُ من ثمن الخطأ**: مقطعٌ لا هُويّةَ له تُحفَظ
   *    مسودّتُه بالنصّ كما كانت تُحفَظ قبل هذا النظام كلِّه. وربطٌ
   *    خاطئٌ يكتب في مذاكرة جملةٍ أخرى ولا سبيلَ إلى كشفه.
   */
  const right = new Array(keys.length).fill(-1);
  let to = rows.length - 1;
  for (let i = keys.length - 1; i >= 0; i -= 1) {
    const key = keys[i];
    if (!key) continue;
    for (let j = to; j >= 0; j -= 1) {
      if (rows[j] === key) { right[i] = j; to = j - 1; break; }
    }
  }

  return left.map((j, i) => (j === right[i] ? j : -1));
}

/**
 * ما اشتُقّ من كلّ مقطعٍ في جلسة — الخريطةُ التي ترسمها الشاشة.
 *
 * @returns {Promise<Map<number, {draft: object, how: string}>>}
 *          المفتاحُ **رقمُ المقطع في الجلسة**.
 */
export async function materialForSegments(record, segmentTexts, { sceneId = null } = {}) {
  const bySentence = await materialMap(record, { sceneId });
  const rows = sentencesOf(record);
  const byId = new Map();
  rows.forEach((one) => {
    const hit = bySentence.get(one.index);
    if (one.id && hit) byId.set(one.id, hit);
  });

  const ids = alignSegments(record, segmentTexts);

  /*
   * ⚠️ **فهرسُ النصّ يُبنى مرّةً — لا `findIndex` لكلّ مقطع** (بند ٦١).
   *
   *    كانت هنا `rows.findIndex(...)` داخل حلقةِ المقاطع. وهي غير
   *    مرئيّةٍ في نصٍّ فيه خمسُ جمل، وتصير `O(ن²)` في نصٍّ فيه أربعمئة:
   *    قاسها المِجَسُّ الحيُّ فوجدها ١٨٢ms لسجلٍّ **بلا معرّفات** —
   *    وهو الحالُ الغالبُ لأنّ المعرّفات لا تُولَد إلّا عند أوّل ربط.
   *    والفهرسُ يُنزلها إلى `O(ن)`.
   *
   * ⚠️ **وأوّلُ تطابقٍ يفوز** كما كانت `findIndex` تمامًا — لا تغييرَ
   *    في السلوك، تغييرٌ في الكلفة وحدَها.
   */
  const rowByKey = new Map();
  rows.forEach((one) => {
    const k = subjectKey(one.text);
    if (k && !rowByKey.has(k)) rowByKey.set(k, one.index);
  });

  const out = new Map();
  segmentTexts.forEach((text, i) => {
    const id = ids[i];
    /*
     * ═══════════════════════════════════════════════════════════
     * ⚠️ **مقطعٌ عُرفت جملتُه لا يستعير من غيرها — ولو خلَت جملتُه**
     * ═══════════════════════════════════════════════════════════
     *
     * كان الشرطُ `if (id && byId.has(id))` ثمّ يسقط الباقي كلُّه إلى
     * الرجوع بالنصّ. ومعناه أنّ مقطعًا **عُرفت هُويّتُه يقينًا** ولا
     * مسودّةَ له كان يُعطى مسودّةَ أوّلِ جملةٍ نصُّها مثلُه.
     *
     * وأمسكها المِجَسُّ الحيّ: نصٌّ فيه «Спаси́бо большо́е.» مرّتين،
     * حُسمت مسودّتُه للأولى بضغطةٍ منك — فأضاءت الشارةُ على الثانية
     * أيضًا وفتحت لها **نفسَ المسودّة**. أي أنّ الحسمَ الذي طلبناه
     * منك لم يحسم شيئًا.
     *
     * فالرجوعُ بالنصّ لِمَن **لا هُويّةَ له** (`id === null`): مقطعٌ
     * حُرِّر نصُّه بعد بناء الجلسة، أو سجلٌّ لم تُولَد معرّفاتُه بعد.
     * وأمّا مَن عُرف فجوابُه في الخريطة — ولو كان الجوابُ «لا شيء».
     */
    if (id) {
      if (byId.has(id)) out.set(i, byId.get(id));
      return;
    }
    const at = rowByKey.get(subjectKey(text));
    if (at !== undefined && bySentence.has(at)) out.set(i, bySentence.get(at));
  });
  return out;
}

/**
 * يربط مسودّةً بجملةٍ بمعرّفها الثابت — **وهذه هي لحظةُ ميلاد الهُويّة**.
 *
 * ⚠️ **وهنا وحدَها تُكتَب المعرّفات** (بند ٦): لا عند القراءة، ولا عند
 *    فتح شاشة. فسجلٌّ لم تربط به شيئًا قطُّ لا يتغيّر ولا يتّسخ ولا
 *    يُرفَع إلى Drive بلا سبب.
 *
 * @returns {Promise<{sentenceId: string, relation: object|null}>}
 */
export async function attachDraft(record, index, draftId, { updateRecord }) {
  const { ensureIds, SENTENCE_IDS } = await import('./sentence-identity.js');
  const { ids, changed } = ensureIds(record);
  const sentenceId = ids[index];
  if (!sentenceId) throw new Error('الجملة دي مش موجودة في النصّ');

  if (changed) await updateRecord(record.id, { [SENTENCE_IDS]: ids });

  const { link } = await import('../link-service.js');
  const relation = await link(sentenceId, draftId, SENTENCE_DRAFT);
  return { sentenceId, relation };
}

/**
 * يربط مسودّةً بـ**مقطعِ جلسةٍ** — وهذا هو البابُ الذي تنادِيه الشاشة.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **رقمُ المقطع ليس رقمَ الجملة** — وقد كلّفَنا هذا مرّةً
 * ═══════════════════════════════════════════════════════════════
 *
 * `attachDraft` تأخذ **رقمَ الجملة في المصدر**. والشاشةُ لا تملك إلّا
 * رقمَ المقطع في الجلسة. وهما متساويان في الجلسة الكاملة فقط —
 * والجلسةُ الجزئيّة (تختار جملًا بعينها ثمّ «تدرّب عليها») تكسر
 * التساوي بلا أن يظهر شيء: يُربَط الدرسُ بجملةٍ غيرِ التي تنظر إليها.
 *
 * فتُمشَّط المواءمةُ هنا مرّةً واحدةً قبل الكتابة.
 *
 * ⚠️ **وما لم يُطابَق لا يُربَط** — لا يُخمَّن ولا يُقرَّب: نصٌّ مؤقّتٌ
 *    أو جملةٌ حُرِّرت بعد بناء الجلسة تُحفَظ مسودّتُها بالنصّ كما كان
 *    قبل هذا النظام، ويعود `null`. وربطٌ خاطئٌ أسوأُ من لا ربط.
 *
 * @returns {Promise<{sentenceId: string, relation: object}|null>}
 */
export async function attachDraftForSegment(
  record, segmentTexts, segmentIndex, draftId, { updateRecord }
) {
  if (!record || !draftId) return null;
  const at = alignSegmentRows(record, segmentTexts)[segmentIndex];
  if (at === undefined || at < 0) return null;
  return attachDraft(record, at, draftId, { updateRecord });
}

/** يفكّ ارتباطَ مسودّةٍ بجملة — ولا يمسّ المسودّة نفسَها (بند ٤٨). */
export async function detachDraft(sentenceId, draftId) {
  const { unlink } = await import('../link-service.js');
  return unlink(sentenceId, draftId, SENTENCE_DRAFT);
}
