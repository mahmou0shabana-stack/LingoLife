/**
 * ⚠️ **هذا السؤالُ هو الذي يحلّ التعارض** — ويستحقّ الشرحَ كاملًا.
 *
 * انظر إلى نصّين متطابقَي الشكل تمامًا:
 *
 *     Документы            ←  عنوانٌ روسيٌّ فوق فقرةٍ عربيّة
 *
 *     تم توقيع المستند.
 *
 * و:
 *
 *     содержа́ть            ←  مقطعٌ روسيٌّ وترجمتُه
 *
 *     يحتوي على / يتضمن
 *
 * سطرٌ سيريليٌّ قصيرٌ وحدَه، ثمّ فراغ، ثمّ سطرٌ عربيّ. **لا فرقَ في
 * الشكل**، والمطلوبُ منهما متضادّ: الأوّلُ لا يُقرَن (يحرسه اختبارُ
 * §٣١ منذ WS-D)، والثاني **يجب** أن يُقرَن.
 *
 * فما الذي يفرّق؟ **السياقُ لا الشكل.** الثاني يعيش داخل وثيقةٍ فيها
 * «الإحساس:» و«أمثلة:» و«القالب:» وفواصلُ زخرفيّة — أي داخل مسودّةٍ
 * قالبُها معروف. والأوّلُ نصٌّ ثنائيٌّ عارٍ.
 *
 * فالمحلّلُ يسأل أوّلًا: **هل هذه مسودّة؟** ثمّ يقرأ بالقواعد المناسبة.
 * وبهذا يكسب القالبُ الثابتُ دقّتَه بلا أن يخسر النصُّ العاديُّ حَذَره.
 *
 * ⚠️ **والعتبةُ محافِظة**: عنوانان معروفان، أو عنوانٌ وفاصلٌ زخرفيّ.
 *    وعنوانٌ واحدٌ وحدَه لا يكفي — «مقارنة:» قد تقع في أيّ نصّ.
 *
 * @param {string} text
 * @returns {boolean}
 */
export function looksDraft(text) {
  const lines = String(text || '').split('\n');
  let labels = 0;
  let bars = 0;
  for (const line of lines) {
    if (matchSection(line)) labels += 1;
    else if (isSeparator(line)) bars += 1;
    if (labels >= 2 || (labels >= 1 && bars >= 1)) return true;
  }
  return false;
}

