/**
 * LingoLife — التقطيعُ المقطعيّ (WS52 · `RU_SYLLABIFICATION`)
 *
 * قانونُ الرنين الصاعد (закон восходящей звучности): المقطعُ يميل إلى
 * الانتهاء بحركة، والعنقودُ بين حركتين ينضمّ إلى المقطع التالي ما دام
 * رنينُه صاعدًا نحو حركته.
 *
 * ⚠️ **وثقةُ هذه القاعدة متوسّطةٌ لا عالية — مكتوبةٌ كذلك في المواصفة.**
 *    المصدرُ نفسُه ينبّه أن القانونَ لا يُدرَّس في المدارس وأن قواعدَ
 *    التقطيع الإملائيّ لا توضّح مداه. فالحالاتُ الشائعةُ مضبوطةٌ
 *    ومختبَرة، والعناقيدُ النادرةُ قد تُقسَّم بغير ما يفعله لغويّ.
 *    وقلتُها هنا لأن **تقطيعًا يبدو واثقًا وهو مختلَفٌ فيه** أسوأُ من
 *    تقطيعٍ يقول عن نفسه إنه تقريب.
 */

import { isVowel, sonority } from './alphabet.js';

/**
 * يقسّم كلمةً إلى مقاطع.
 *
 * الخوارزميّة:
 *  ١ · كلُّ حركةٍ نواةُ مقطع (فعددُ المقاطع = عددُ الحركات).
 *  ٢ · ما قبل أوّل حركةٍ يلتصق بالمقطع الأوّل.
 *  ٣ · العنقودُ بين حركتين يُقسَم عند النقطة التي يصعد بعدها الرنينُ
 *      حتى الحركة التالية؛ وعمليًّا: **الساكنُ الأخيرُ من العنقود
 *      يذهب دائمًا مع الحركة التالية**، ومَن قبله ينضمّ إليه ما دام
 *      رنينُه أقلَّ من الذي يليه (أي ما دام الصعودُ محفوظًا).
 *  ٤ · ما بعد آخر حركةٍ يلتصق بالمقطع الأخير.
 *
 * @param {string} word كلمةٌ بلا علامة نبر، صغيرةُ الحروف
 * @returns {{ text: string, ordinal: number }[]}
 */
export function syllabify(word) {
  const chars = [...String(word || '').toLowerCase()];
  const vowelAt = [];
  chars.forEach((ch, i) => { if (isVowel(ch)) vowelAt.push(i); });

  /* ⚠️ كلمةٌ بلا حركة (`в`, `к`, `с`) لا تُقسَّم — ولا تُختلَق لها مقاطع. */
  if (!vowelAt.length) return [];

  const bounds = [0];

  for (let v = 0; v < vowelAt.length - 1; v += 1) {
    const start = vowelAt[v] + 1;      // أوّلُ ساكنٍ بعد الحركة الحالية
    const end = vowelAt[v + 1];        // موضعُ الحركة التالية
    const cluster = end - start;       // طولُ العنقود بينهما

    if (cluster === 0) {
      /* حركتان متجاورتان: الحدُّ بينهما مباشرةً — `на-у-ка`. */
      bounds.push(end);
      continue;
    }
    if (cluster === 1) {
      /* ساكنٌ واحد: يذهب مع التالي — `мо-ло-ко`. */
      bounds.push(start);
      continue;
    }

    /*
     * عنقودٌ من ساكنين فأكثر. نبدأ من الساكن الأخير (يذهب مع الحركة
     * التالية قطعًا) ونمدّ الحدَّ يسارًا ما دام الرنينُ صاعدًا.
     *
     * ⚠️ **وهذا ما يجعل `се-стра` لا `сест-ра`**: `стр` رنينُها
     *    ١ ← ١ ← ٣ صاعدٌ فتبدأ المقطعَ كلُّها. وهي الحالةُ التي يخطئ
     *    فيها التقطيعُ الساذجُ «ساكنٌ واحدٌ للتالي والباقي للسابق».
     *
     * ⚠️ **و`ь`/`ъ` شفّافتان في هذا المسح — وكانتا ليستا.**
     *    رنينُهما صفرٌ فكانتا تكسران الصعودَ وتصنعان حدًّا وهميًّا:
     *    `просьба` تخرج `прос-ьба` — ومقطعٌ يبدأ بعلامةٍ لا صوتَ لها
     *    ليس مقطعًا أصلًا. فالمسحُ يتجاهلهما، وتبقى كلٌّ منهما لاصقةً
     *    بساكنها لأنها **صفتُه** لا جارتُه.
     */
    const scan = [];
    for (let p = start; p < end; p += 1) {
      if (chars[p] !== 'ь' && chars[p] !== 'ъ') scan.push(p);
    }
    if (!scan.length) { bounds.push(end); continue; }

    let s = scan.length - 1;
    while (s > 0 && sonority(chars[scan[s - 1]]) <= sonority(chars[scan[s]])) s -= 1;
    const cut = scan[s];

    /*
     * ⚠️ **ورنّانةٌ تسبق عائقةً تبقى مع المقطع السابق.** `сол-нце`:
     *    `л` (٣) قبل `н`(٣)/`ц`(١) — لا يصعد الرنينُ من `л` إلى `ц`،
     *    فلا تجوز `со-лнце` بقانون الصعود. والشرطُ أعلاه يمنعها لأن
     *    `sonority(л) > sonority(ц)`.
     */
    bounds.push(cut);
  }

  const out = [];
  for (let i = 0; i < bounds.length; i += 1) {
    const from = bounds[i];
    const to = i + 1 < bounds.length ? bounds[i + 1] : chars.length;
    out.push({ text: chars.slice(from, to).join(''), ordinal: i });
  }
  return out;
}

/**
 * أيُّ مقطعٍ يقع فيه حرفُ العلّة رقم `ordinal`؟
 * ⚠️ **وهو نفسُه `ordinal`** — لأن لكلّ مقطعٍ حركةً واحدة. الدالّةُ
 *    موجودةٌ لتُسمّي هذه الحقيقةَ لا لتحسبها، فلا يظنّ قارئٌ أن ثمّة
 *    تحويلًا خفيًّا.
 */
export function syllableOfVowel(ordinal) {
  return ordinal;
}
