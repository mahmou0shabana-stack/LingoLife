/**
 * ⚠️ **ولا تُفرَض Markdown على نصٍّ عاديّ** (بند ٢٣).
 *
 * برومبتاتُك ليست Markdown: فيها «§1» و«SECTION 4» و«القواعد:» و
 * «FINAL DIRECTIVE» وفواصلُ «━━━». وتشغيلُ مُصيِّرِ Markdown عليها
 * يحوّل `#` و`*` و`_` إلى تنسيقٍ لم تقصده، ويُفسد ما ستنسخه.
 *
 * فالمخطَّطُ **مشتقٌّ للتنقّل فقط**: أسطرٌ تبدو عناوينَ تُعرَض قائمةً
 * جانبيّةً تقفز إليها. والنصُّ يُعرَض كما هو، حرفًا بحرف.
 */
const HEADING_RULES = [
  /* «§1» و«§ ٣» — علامةُ قسمٍ صريحة. */
  { re: /^\s*§\s*[\d٠-٩]+/u, kind: 'section' },
  /* «SECTION 4» · «PART 2» · «STEP 3» — لاتينيٌّ كبيرٌ ثم رقم. */
  { re: /^\s*(SECTION|PART|STEP|PHASE|RULE|BLOCK)\s+[\dIVX]+/i, kind: 'section' },
  /* سطرٌ مرقَّمٌ قصير: «12. القواعد» أو «٣) الهدف». */
  { re: /^\s*[\d٠-٩]{1,3}\s*[.)\-–—]\s*\S/u, kind: 'numbered' },
  /* «القواعد:» — عربيٌّ قصيرٌ ينتهي بنقطتين. */
  { re: /^\s*[^\n]{2,48}[:：]\s*$/u, kind: 'label' },
  /* «FINAL DIRECTIVE» — لاتينيٌّ كبيرٌ كلُّه. */
  { re: /^\s*[A-Z][A-Z\s/&-]{4,48}$/u, kind: 'caps' },
  /* عنوانُ Markdown — يُقبَل إن وُجد، ولا يُفرَض. */
  { re: /^\s*#{1,4}\s+\S/u, kind: 'hash' },
];

/** فاصلٌ زخرفيٌّ — يُعَدّ حدًّا لا عنوانًا. */
const BAR = /^[\s━─―—–\-=*_·•~＝▬]{4,}$/;

/**
 * يستخرج مخطَّطَ عناوين — **للتنقّل لا للتنسيق**.
 *
 * ⚠️ **ولا يُعرَض مخطَّطٌ لبرومبتٍ قصير** (بند ٢٤): قائمةُ قفزٍ فوق
 *    عشرين سطرًا زينةٌ تسرق عرضًا على تابلت. والعتبةُ في الشاشة لا هنا،
 *    وهذه تعطي ما وجدَته وتترك القرار.
 *
 * @param {string} text
 * @returns {{line: number, text: string, kind: string}[]}
 */
export function outlineOf(text) {
  const lines = String(text || '').split('\n');
  const out = [];

  for (let i = 0; i < lines.length; i += 1) {
    const line = lines[i];
    const clean = line.trim();
    if (!clean || BAR.test(clean)) continue;
    /* عنوانٌ لا فقرة: سطرٌ قصيرٌ نسبيًّا. */
    if (clean.length > 80) continue;

    const rule = HEADING_RULES.find((one) => one.re.test(line));
    if (!rule) continue;

    /*
     * ⚠️ **وسطرٌ مرقَّمٌ داخل قائمةٍ ليس عنوانًا.** «1. افعل كذا» و
     *    «2. ثمّ كذا» بندان في قائمة، لا قسمان. والفارقُ أنّ العنوانَ
     *    يقف وحدَه: سطرٌ فارغٌ قبله **و**بعده.
     *
     * ⚠️ **وكانت هنا `||` فكشفها الاختبارُ ٢١.** «فارغٌ قبله **أو**
     *    بعده» شرطٌ يستوفيه **أوّلُ بندٍ في كلّ قائمةٍ وآخِرُها** دائمًا:
     *    الأوّلُ يسبقه فراغُ ما قبل القائمة، والآخِرُ يتبعه فراغُ ما
     *    بعدها. فكان مخطَّطُ برومبتٍ فيه خمسُ قوائمَ يمتلئ بعشرة عناوينَ
     *    مخترَعة — وهو بالضبط ما ينهى عنه البندان ٢٣ و٢٤: مخطَّطٌ يسرق
     *    عرضًا على تابلت ثمّ يقفز بك إلى غير ما وعد.
     */
    if (rule.kind === 'numbered') {
      const alone = !(lines[i - 1] || '').trim() && !(lines[i + 1] || '').trim();
      if (!alone) continue;
    }

    out.push({ line: i, text: clean.replace(/^#{1,4}\s+/, ''), kind: rule.kind });
  }

  return out;
}

