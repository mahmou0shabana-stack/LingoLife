/**
 * LingoLife — الطبقات: زرُّ الرجوع يقفل المفتوح لا الصفحة
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ ثلاثة بلاغاتٍ من جهازك سببُها واحد
 * ═══════════════════════════════════════════════════════════════
 *
 * > «لما اجي أرجع لورا والصورة مفتوحة، الصورة مبتتقفلش — الصفحة نفسها
 * > بترجع لورا.»
 * > «النوافذ الصغيرة: أما أرجع لورا وهي مفتوحة المفروض هي اللي تتقفل
 * > مش الصفحة الأصلية. **وقيس على كده كل النوافذ في البرنامج.**»
 *
 * والسبب أن التطبيق لم يكن يعرف الفرق بين **صفحةٍ** و**طبقةٍ فوقها**.
 * فزرُّ الرجوع — سواءٌ زرُّ النظام في أندرويد أو زرُّ القشرة — كان
 * يتنقّل في المسارات دائمًا، والطبقةُ المفتوحة تبقى معلّقةً فوق شاشةٍ
 * تغيّرت تحتها.
 *
 * ═══════════════════════════════════════════════════════════════
 * والحلّ: كل طبقةٍ تحجز مدخلًا في التاريخ
 * ═══════════════════════════════════════════════════════════════
 *
 * ```
 * تفتح نافذة   ──▶  pushState (بلا تغيير المسار)
 * تضغط رجوع    ──▶  popstate  ──▶  نقفل الطبقة العليا ونمنع التنقّل
 * تقفلها بزرّ  ──▶  نسحب مدخلَ التاريخ كي لا يبقى معلّقًا
 * ```
 *
 * ⚠️ **و`pushState` بلا مسار عمدًا**: المسار لا يتغيّر، فلا يُطلَق
 *    `hashchange` ولا يُعيد الموجِّه الرسم. الطبقة ليست وجهة.
 *
 * ⚠️ **والإغلاق بزرٍّ يسحب مدخلَه.** بدون ذلك يتراكم في التاريخ مدخلٌ
 *    ميّت لكل نافذةٍ فتحتَها وأغلقتَها، فتضغط رجوع ثلاث مرّات ولا يحدث
 *    شيء. وهو أسوأ من العطب الأصلي لأنه لا يُفهَم.
 */

/** مكدّس الطبقات المفتوحة — الأعلى آخرًا. */
const stack = [];

/**
 * كم `popstate` علينا تجاهله.
 *
 * ⚠️ `history.back()` غيرُ متزامن: نناديها عند الإغلاق بزرّ، فيصل
 *    `popstate` بعد لحظة. ولولا هذا العدّاد لظنّه المستمع ضغطةَ رجوعٍ
 *    منك فأغلق الطبقة **التالية** — نافذتان تُغلقان بضغطةٍ واحدة.
 */
let ignore = 0;

/** هل الإغلاق الجاري سببُه التاريخ؟ فلا نسحب مدخلًا سُحب أصلًا. */
let fromHistory = false;

/**
 * يسجّل طبقةً مفتوحة.
 *
 * @param {() => void} close ما يُنفَّذ حين يطلب المستخدم إغلاقها
 * @param {{ id?: string }} [meta] اسمٌ للتشخيص
 * @returns {object} مقبضٌ يُمرَّر إلى `dropLayer`
 */
export function pushLayer(close, { id = 'layer' } = {}) {
  const layer = { id, close };
  stack.push(layer);
  window.history.pushState({ lingolifeLayer: id }, '');
  return layer;
}

/**
 * يرفع طبقةً أُغلقت — **من المكدّس ومن التاريخ**.
 *
 * تُنادى من داخل الطبقة نفسها بعد أن تُغلق. ولا تُغلق شيئًا: الطبقة
 * أدرى بكيفية إغلاق نفسها.
 */
export function dropLayer(layer) {
  const index = stack.lastIndexOf(layer);
  if (index < 0) return;
  stack.splice(index, 1);

  if (fromHistory) return;
  ignore += 1;
  window.history.back();
}

/**
 * يُغلق الطبقة العليا إن وُجدت.
 * @returns {boolean} هل أُغلق شيء؟ فمَن ينادينا لا يتنقّل بعدها.
 */
export function closeTop() {
  const layer = stack[stack.length - 1];
  if (!layer) return false;
  layer.close();
  return true;
}

/** هل فوق الصفحة شيءٌ مفتوح؟ — لزرّ الرجوع في القشرة. */
export const hasLayer = () => stack.length > 0;

/** أسماء ما هو مفتوح — للتشخيص وللاختبار. */
export const openLayers = () => stack.map((layer) => layer.id);

/**
 * يبدأ الاستماع لزرّ الرجوع.
 *
 * ⚠️ يُنادى مرّةً واحدة من `app.js` قبل الموجِّه: مستمعُ `popstate`
 *    هنا يجب أن يسبق أي إعادة رسم.
 */
export function startLayers() {
  window.addEventListener('popstate', () => {
    if (ignore > 0) {
      ignore -= 1;
      return;
    }
    if (!stack.length) return;

    const layer = stack.pop();
    fromHistory = true;
    try {
      layer.close();
    } finally {
      fromHistory = false;
    }
  });
}

/**
 * ⚠️ **للاختبارات وحدها** — تُفرِّغ المكدّس بلا لمس التاريخ.
 *    شاشةٌ تُغادَر وطبقةٌ عالقة تعني زرَّ رجوعٍ لا يفعل شيئًا.
 */
export function resetLayers() {
  stack.length = 0;
  ignore = 0;
  fromHistory = false;
}
