/**
 * اتّجاهُ فقرةٍ — **لكلّ كتلةٍ اتّجاهُها** (بند ٢٦).
 *
 * ⚠️ **ولمَ لا `dir="auto"` وحدَها؟** لأنّها تحكم بأوّل حرفٍ ذي اتّجاه.
 *    وسطرٌ يبدأ بـ«§1» أو بقوسٍ أو برقمٍ ثمّ يتبعه عربيٌّ يُقرأ لاتينيًّا
 *    فتقفز نقطتُه إلى الطرف الخطأ. فالحكمُ هنا **بالغلبة** لا بالأوّل.
 *
 * @param {string} block
 * @returns {'rtl'|'ltr'}
 */
export function blockDir(block) {
  const text = String(block || '');
  const rtl = (text.match(/[؀-ۿݐ-ݿ]/g) || []).length;
  const ltr = (text.match(/[A-Za-zЀ-ӿ]/g) || []).length;
  if (!rtl && !ltr) return 'rtl';
  return rtl >= ltr ? 'rtl' : 'ltr';
}

/**
 * يقسّم نصَّ البرومبت إلى كتلٍ للعرض — **بلا تغيير حرفٍ واحد**.
 *
 * ⚠️ والسطورُ الفارغةُ تُحفَظ داخل الكتل: هي جزءٌ من شكل البرومبت،
 *    وحذفُها يغيّر ما ستنسخه.
 *
 * @returns {{text: string, dir: string}[]}
 */
export function readingBlocks(text) {
  const src = String(text || '');
  if (!src) return [];
  return src.split(/\n{2,}/).map((block) => ({ text: block, dir: blockDir(block) }));
}
