/**
 * LingoLife — فهرسُ «لغتي» المحفوظ وبابُ إبطاله (WS-J)
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **ورقةٌ لا تستورد شيئًا — والسببُ حلقةُ استيرادٍ وقعت قبلُ**
 * ═══════════════════════════════════════════════════════════════
 *
 * الحفظُ من الشادوينج يجب أن يُبطِل الفهرسَ (وإلّا فتحتَ «لغتي» بعده
 * فرأيتَ حالةً قديمة). فلو وضعنا الذاكرةَ في `my-language.js` لَاحتاج
 * `saved-service` أن يستورده — وهو يستورد `import-v2` و`counting`
 * و`source-registry`، أي أن حفظَ كلمةٍ يحمّل محرّكَ التحليل كلَّه.
 *
 * وقد وقع مثلُ هذا حرفيًّا في WS-H (`cloud-service → cloud-sync →
 * sync-journal → cloud-service`) وحُلَّ بورقةٍ لا تستورد أحدًا. فهذه
 * أختُها: تعرف كائنًا واحدًا ولا تعرف من صنعه.
 *
 * ⚠️ **والإبطالُ بالكتابة لا بالوقت.** «أعِد البناءَ كلّ خمس دقائق»
 *    يعني رقمًا بائتًا بعد حفظِك مباشرةً، أو إعادةَ بناءٍ لا سببَ لها.
 *    فمن يكتب شيئًا يمسّ لغتَك ينادي `invalidateLanguage()`.
 */

let index = null;

/** الفهرسُ المحفوظ، أو `null` إن لم يُبنَ بعدُ أو أُبطِل. */
export const cachedLanguage = () => index;

/** يحفظ فهرسًا جديدًا. */
export function cacheLanguage(built) {
  index = built || null;
  return index;
}

/**
 * يُبطِل الفهرس — يُنادى من **كلّ** كتابةٍ تمسّ لغتك.
 *
 * ⚠️ ولا يُعاد البناءُ هنا: الإبطالُ رخيصٌ والبناءُ ليس كذلك، ومن
 *    حفظ كلمةً وهو في شاشة التدريب لا ينبغي أن يدفع ثمنَ بناءِ
 *    فهرسٍ لن يراه.
 */
export function invalidateLanguage() {
  index = null;
}
