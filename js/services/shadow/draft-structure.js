/* ٢) الفواصلُ الزخرفيّة (بند ٣٠-L)                                    */
/* ================================================================== */

/**
 * سطرٌ زخرفيٌّ خالص: شُرَطٌ أو نجومٌ أو مربّعاتٌ متكرّرة.
 *
 * ⚠️ **ولا يُعدّ محتوًى ولا ضوضاءً تحتاج مراجعة.** كان المحلّلُ يخرج
 *    منه وحدةً فارغةً (`ru:'' ar:''`) تظهر في المراجعة صفًّا لا معنى
 *    له — ثلاثةُ صفوفٍ كهذه في مسودّةٍ واحدة.
 */
export function isSeparator(line) {
  const clean = String(line || '').trim();
  if (!clean) return false;
  return /^[\s━─―—–\-=*_.·•~＝▬]{3,}$/.test(clean);
}

/* ================================================================== */
/* ٣) بدائلُ الترجمة: الشرطةُ المائلة (بنود ٦ و٧ و٨)                   */
/* ================================================================== */

/**
 * يقسم نصًّا على «/» إلى بدائل — **بحذرٍ ووعيٍ باللغة**.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ «/» في مسودّاتك تعني **معانيَ بديلةً لعنصرٍ واحد** لا عنصرين
 * ═══════════════════════════════════════════════════════════════
 *
 *     подтвержде́ние
 *     إثبات / تأكيد
 *
 * روسيٌّ **واحد**، ومجموعةُ ترجمةٍ **واحدة**، وبديلان. وقراءتُها
 * «عنصرين» تصنع عناصرَ وهميّةً لا وجودَ لها في مسودّتك.
 *
 * ⚠️ **وهي في الروسيّ صيغٌ لا ترجمات** (بند ٧):
 *
 *     должен / должны́ + быть + اسم مفعول
 *
 *   فالقسمةُ نفسُها تصلح، والتسميةُ تختلف: تلك «صيغٌ بديلة».
 *
 * ⚠️ **وما لا يُقسَم:**
 *   · التواريخُ والكسور: «2025/09/01» و«1/2» — أرقامٌ حول الشرطة.
 *   · العناوينُ والمسارات: «ISO/IEC» — لاتينيٌّ ملتصقٌ بلا مسافات
 *     وطرفاه قصيران جدًّا.
 *   · طرفٌ فارغٌ أو كلُّه ترقيم.
 *
 * @param {string} text
 * @returns {string[]} البدائل — عنصرٌ واحدٌ إن لم تكن هناك قسمة
 */
export function splitAlternatives(text) {
  const clean = String(text || '').trim();
  if (!clean || !clean.includes('/')) return clean ? [clean] : [];

  /* ⚠️ تاريخٌ أو كسرٌ: أرقامٌ على الجانبين مباشرةً — لا تُقسَم. */
  if (/\d\s*\/\s*\d/.test(clean)) return [clean];

  const parts = clean.split('/').map((one) => one.trim()).filter(Boolean);
  if (parts.length < 2) return [clean];

  /*
   * ⚠️ **ولا يُقسَم رمزٌ ملتصق.** «ISO/IEC 27001» تُقرأ اسمًا واحدًا:
   *    الفاصلُ بلا مسافاتٍ حولَه **و**أحدُ طرفيه كلمةٌ واحدةٌ قصيرةٌ
   *    بلا حروفٍ عربيّةٍ ولا سيريليّة. والشرطُ مركَّبٌ عمدًا كي لا
   *    يمنعَ «إثبات/تأكيد» الملتصقةَ أيضًا.
   */
  const spaced = /\s\/|\/\s/.test(clean);
  const wordy = parts.every((one) => /[؀-ۿЀ-ӿ]/.test(one));
  if (!spaced && !wordy) return [clean];

  /* بديلٌ كلُّه ترقيمٌ أو رقمٌ ليس بديلًا. */
  const real = parts.filter((one) => /[\p{L}]/u.test(one));
  return real.length >= 2 ? real : [clean];
}

/**
 * الترجمةُ الأساسيّةُ والبدائل — **اشتقاقٌ عند القراءة لا تخزين** (بند ٦).
 *
 * ⚠️ **ولا هجرةَ بيانات** (بند ٤٤): المخزَّنُ يبقى سلسلةً عربيّةً واحدةً
 *    كما كُتبت — «إثبات / تأكيد». والبدائلُ تُقرأ منها في كلّ مرّة.
 *    فمسودّاتُك القديمةُ تفهم نفسَها من غير أن يُمسّ صفٌّ منها.
 *
 * ⚠️ **والأولى ليست دائمًا اختيارَك** (بند ٨): `primary` رقمُ اختيارِك
 *    إن اخترتَ، والافتراضُ صفرٌ — وهو افتراضٌ لا حكم.
 *
 * @param {string} arabic النصُّ المخزَّن
 * @param {number} [primary] فهرسُ البديل المفضَّل
 * @returns {{primary: string, alts: string[], all: string[], hasAlts: boolean}}
 */
export function translationView(arabic, primary = 0) {
  const all = splitAlternatives(arabic);
  if (!all.length) return { primary: '', alts: [], all: [], hasAlts: false };
  const at = Number.isInteger(primary) && primary >= 0 && primary < all.length ? primary : 0;
  return {
    primary: all[at],
    alts: all.filter((_, i) => i !== at),
    all,
    hasAlts: all.length > 1,
  };
}

