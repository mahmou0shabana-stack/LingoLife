/**
 * ⚠️ **الكشفُ متحفّظٌ عمدًا** (بند ٢٠).
 *
 * القوسان المربّعان يقعان في نصوصٍ كثيرةٍ لا علاقةَ لها بالقوالب:
 *
 *   · روابطُ Markdown:      `[النصّ](https://…)`
 *   · مصفوفاتُ كود:          `arr[0]` · `[1, 2, 3]`
 *   · أصنافُ التعابير:       `[a-z]` · `[^\d]`
 *   · مراجعُ ترقيم:          `[1]` · `[ref]`
 *
 * والقاعدةُ التي تفصل: **المتغيّرُ نصٌّ بشريٌّ يطلب منك شيئًا**. فيه
 * حروفٌ (لا أرقامٌ وحدها)، وليس رمزًا برمجيًّا، ولا يتبعه قوسُ رابط.
 *
 * ⚠️ **وما شككنا فيه يُترَك نصًّا كما هو** — لا يُعرَض متغيّرًا ولا
 *    يُمَسّ. لأن متغيّرًا مخترَعًا يجعلك تملأ حقلًا لا محلَّ له، ثمّ
 *    تنسخ نصًّا فيه ثقبٌ مكان ما «ملأتَه».
 */

/** رمزٌ برمجيٌّ صِرف — لا يُقرأ متغيّرًا مهما كان بين قوسين. */
const CODE_LIKE = /^[\s\d.,:;|/\\^$*+?{}()[\]<>=!&%#@~`'"-]*$/;

/** أصنافُ التعابير المنتظمة الشائعة: `a-z` و`^\d` و`0-9`. */
const REGEX_CLASS = /^\s*\^?[\\\w]-?[\\\w](-[\\\w])?\s*$/;

/**
 * يكشف متغيّراتِ قالبٍ داخل نصّ.
 *
 * @param {string} text
 * @returns {{name: string, raw: string, at: number[]}[]}
 *          `name` الاسمُ المعروض · `raw` ما بين القوسين كما هو ·
 *          `at` مواضعُ كلّ ظهورٍ في النصّ.
 */
export function findPlaceholders(text) {
  const src = String(text || '');
  const found = new Map();

  /* ⚠️ `[^\[\]]` كي لا يبتلع قوسٌ مفتوحٌ نصفَ الملفّ بحثًا عن نظيره. */
  const re = /\[([^[\]\n]{1,120})\]/g;
  let hit = re.exec(src);
  while (hit) {
    const raw = hit[1];
    const at = hit.index;
    re.lastIndex = at + hit[0].length;

    if (looksFillable(src, raw, at + hit[0].length)) {
      const key = raw.trim();
      if (!found.has(key)) found.set(key, { name: key, raw, at: [] });
      found.get(key).at.push(at);
    }
    hit = re.exec(src);
  }

  return [...found.values()];
}

/** هل يبدو ما بين القوسين حقلًا يملؤه إنسان؟ */
function looksFillable(src, raw, after) {
  const inner = raw.trim();
  if (!inner) return false;

  /* رابطُ Markdown: يتبع القوسَ المربّع قوسٌ مستدير. */
  if (src[after] === '(') return false;

  /* لا حروفَ أصلًا — رقمٌ أو رمز. */
  if (!/\p{L}/u.test(inner)) return false;
  if (CODE_LIKE.test(inner)) return false;
  if (REGEX_CLASS.test(inner)) return false;

  /* مرجعٌ لاتينيٌّ قصيرٌ بلا مسافة: `[ref]` و`[i]` و`[TODO]`. */
  if (!/\s/.test(inner) && inner.length <= 4) return false;

  /*
   * ⚠️ **ولا يُقسَّم سطرٌ كوديّ**: `data[userName]` قوسُه لاحقٌ لكلمةٍ
   *    بلا فاصل — وهي فهرسةٌ لا حقل.
   */
  const before = src[src.lastIndexOf('[', after - 1) - 1];
  if (before && /[\w$)\]]/.test(before)) return false;

  return true;
}

/**
 * يملأ قالبًا بقيمٍ أعطيتَها — **ويعيد نسخةً**.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **القالبُ المحفوظ لا يُمَسّ أبدًا** (بندا ٢١ و٥٤ · قاعدة ٤)
 * ═══════════════════════════════════════════════════════════════
 *
 * هذه أخطرُ نقطةٍ في الميزة كلِّها. لو كُتبت القيمُ في نصّ البرومبت
 * لصار قالبُك — الذي بنيتَه في شهور — نسخةً واحدةً من استعمالٍ واحد.
 * فالقيمُ حالةُ واجهةٍ عابرة، وهذه الدالّةُ **خالصة**: تأخذ نصًّا وخريطة
 * قيمٍ وتعيد سلسلةً جديدة، ولا تلمس مصدرَها.
 *
 * ⚠️ **وما لم تملأه يبقى كما هو** — لا يُحذَف ولا يُترَك فراغًا. فترى
 *    في المعاينة أنّك نسيتَ حقلًا، بدل أن تنسخ نصًّا فيه ثقب.
 *
 * @param {string} text القالب
 * @param {Record<string,string>} values الاسمُ ← القيمة
 * @returns {string} نسخةٌ معبّأة
 */
export function fillTemplate(text, values = {}) {
  const src = String(text || '');
  return src.replace(/\[([^[\]\n]{1,120})\]/g, (whole, raw, at) => {
    if (!looksFillable(src, raw, at + whole.length)) return whole;
    const value = values[raw.trim()];
    return value !== undefined && String(value).trim() ? String(value) : whole;
  });
}

/** كم متغيّرًا بقي بلا قيمة — يُقال للمستعمل قبل النسخ. */
export function unfilledCount(text, values = {}) {
  return findPlaceholders(text)
    .filter((one) => !String(values[one.name] ?? '').trim()).length;
}

