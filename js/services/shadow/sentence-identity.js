/**
 * LingoLife — هُويّةُ الجملة الثابتة (WS-SC1 · بنود ٤ و٦ و٣٤ إلى ٣٧)
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **العطبُ الذي كُشف بالتدقيق — والقرارُ الذي غيّره**
 * ═══════════════════════════════════════════════════════════════
 *
 * مسودّةُ المذاكرة كانت تُعرَّف بـ **نصّ الجملة مُطبَّعًا** وحدَه
 * (`studyDrafts.subject`)، وهو قرارٌ مكتوبٌ في رأس `study-draft.js`
 * وله سببٌ وجيهٌ وقتَه: مقاطعُ الظلّ تموت بموت جلستها، فربطُ المسودّة
 * بها يعني ضياعَها عند أوّل إعادةِ بناء.
 *
 * لكنّ ثمنَه ظهر الآن: **جملتان متطابقتان نصًّا تتشاركان مسودّةً
 * واحدة** — لا في النصّ الواحد فحسب بل في التطبيق كلِّه. فـ`Хорошо.`
 * في سكريبتٍ و`Хорошо.` في آخرَ شيءٌ واحد. وهذا بعينه ما يمنعه البندُ
 * ٣٦، ويهدم النموذجَ الذي تقوم عليه هذه التمريرة: **الجملةُ هي الأصل،
 * وما اشتُقّ منها يسكن حولها**.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **ولماذا معرّفاتٌ دائمةٌ على السكريبت لا مرساةٌ محسوبة؟**
 * ═══════════════════════════════════════════════════════════════
 *
 * أرخصُ حلٍّ كان مرساةً محسوبة: «السكريبتُ + النصُّ المُطبَّع + رقمُ
 * التكرار». لا حقلَ يُضاف ولا مسارَ كتابةٍ يُمَسّ. لكنّها **تنكسر عند
 * أوّل تعديلٍ لعلامةِ ترقيم**: النصُّ تغيّر فالمرساةُ تغيّرت فضاعت
 * المسودّة — وهو ما ينهى عنه البندُ ٣٥ نصًّا. وتنكسر كذلك عند إعادةِ
 * ترتيبِ جملتين متطابقتين، لأنّ «رقمَ التكرار» موضعٌ لا هُويّة.
 *
 * فالمعرّفُ هنا **يُولَد مرّةً ويعيش**: يُحفَظ في `scripts.sentenceIds`
 * موازيًا لترتيب `splitSentences`، ويُصان بالمقارنة عند كلّ حفظ. فتعديلُ
 * الجملة يُبقي معرّفَها، وإعادةُ الترتيب تنقله معها، والمتطابقتان
 * تحملان معرّفَين مختلفَين منذ لحظة ميلادهما.
 *
 * ⚠️ **ولا مخزنَ جديدٌ ولا فهرسٌ جديد**: `sentenceIds` حقلٌ يُضاف إلى
 *    سجلٍّ قائم — كما أُضيف `templateKey` و`derivedFromScriptId` من قبل.
 *    فلا ترقيةَ مخطَّطٍ ولا رقمَ نسخةٍ يُرفَع.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **ولا تُكتَب المعرّفاتُ عند القراءة أبدًا** (بند ٦)
 * ═══════════════════════════════════════════════════════════════
 *
 * أسهلُ تنفيذٍ أن تُردَم المعرّفاتُ أوّلَ مرّةٍ يُقرأ فيها السكريبت.
 * ورفضتُه لسببين:
 *
 *   ١) **البندُ ٦ ينهى عن الهجرة الصامتة.** وفتحُ شاشةٍ ليس طلبَ
 *      تعديلِ بيانات.
 *   ٢) **وضجيجُ المزامنة**: كتابةٌ عند القراءة تعني أنّ مجرّدَ تصفّحِ
 *      نصوصك يجعل كلَّ سكريبتٍ «متّسخًا» فيُرفَع إلى Drive بلا سبب.
 *
 * فالمعرّفاتُ تُولَد **عند أوّل ارتباطٍ فعليّ** — أي حين تربط مسودّةً
 * بجملة، وهي اللحظةُ التي تبدأ فيها الهُويّةُ أن تعني شيئًا. وقبلها
 * يعمل النصُّ المُطبَّعُ كما كان يعمل بالضبط.
 */

import { splitSentences } from './segmenter.js';

/** الحقلُ الذي يحمل المعرّفاتِ على سجلّ السكريبت/العقدة. */
export const SENTENCE_IDS = 'sentenceIds';

/**
 * يقسّم نصَّ سكريبتٍ إلى جملٍ — **بنفس القاطع الذي يستعمله الظلّ**.
 *
 * ⚠️ **ووحدةُ القطع واحدةٌ أو لا هُويّة**: لو قطعَت هذه الوحدةُ بقاعدةٍ
 *    وقطعَ الظلُّ بأخرى لاختلف عددُ الجمل، فصار المعرّفُ رقمَ ٧ عند
 *    واحدةٍ ورقمَ ٨ عند الأخرى — وهو أسوأُ من غياب المعرّف.
 */
export function sentenceTexts(text) {
  return splitSentences(text || '', { requireCyrillic: false, minLength: 1 });
}

/** معرّفٌ جديدٌ لجملة — بادئةٌ تُقرأ في التشخيص. */
function newId() {
  return `SEN_${Date.now().toString(36).toUpperCase()}_${
    Math.random().toString(36).slice(2, 10).toUpperCase()}`;
}

/**
 * يوائم معرّفاتِ الجمل بين نصٍّ قديمٍ ونصٍّ جديد.
 *
 * ═══════════════════════════════════════════════════════════════
 * ⚠️ **ثلاثُ مرّاتٍ بترتيبٍ مقصود — والترتيبُ هو المنطق كلُّه**
 * ═══════════════════════════════════════════════════════════════
 *
 * ١) **المطابقُ نصًّا أوّلًا** — وبترتيب التكرار. فجملةٌ لم تتغيّر
 *    تحتفظ بمعرّفها ولو انتقلت من الموضع ٣ إلى ١٧ (بند ٣٧). ومتطابقتان
 *    تأخذ كلٌّ منهما معرّفَها الأصليَّ بترتيب ظهورهما، فلا تتبادلان.
 *
 * ٢) **ثمّ الباقي بالموضع** — الجملةُ التي حُرِّرت في مكانها تبقى هي
 *    هي (بند ٣٥): كان في الموضع ٥ سطرٌ، وصار فيه سطرٌ معدَّل، ولم
 *    يتبقَّ ما يطابقه نصًّا — فهو هو.
 *
 * ⚠️ **والموضعُ هنا ليس هُويّةً** بل آخِرُ دليلٍ بعد استنفاد النصّ.
 *    والفرقُ جوهريّ: البندُ ٣٧ يمنع أن يكون الرقمُ هُويّة، ولا يمنع
 *    أن يكون قرينةً حين يكون كلُّ ما بقي.
 *
 * ٣) **وما بقي بلا نظيرٍ يُولَد جديدًا** — جملةٌ أُضيفت لم تكن، فلا
 *    تُورَّث معرّفَ جملةٍ حُذفت وإلّا ورثت مسودّتَها معها.
 *
 * @param {string[]} before نصوصُ الجمل قبل التعديل
 * @param {string[]} beforeIds معرّفاتُها بنفس الترتيب
 * @param {string[]} after نصوصُ الجمل بعد التعديل
 * @returns {string[]} معرّفاتٌ بطول `after`
 */
export function reconcileIds(before, beforeIds, after) {
  const out = new Array(after.length).fill(null);
  const takenIds = new Set();

  /* طوابيرُ المعرّفات لكلّ نصٍّ قديم — الترتيبُ يحفظ تمييزَ المتطابقات. */
  const byText = new Map();
  before.forEach((text, i) => {
    const id = beforeIds[i];
    if (!id) return;
    if (!byText.has(text)) byText.set(text, []);
    byText.get(text).push(id);
  });

  /* (١) المطابقُ نصًّا — بترتيب التكرار. */
  after.forEach((text, i) => {
    const queue = byText.get(text);
    if (queue && queue.length) {
      const id = queue.shift();
      out[i] = id;
      takenIds.add(id);
    }
  });

  /* (٢) الباقي بالموضع — ما لم يُؤخَذ معرّفُه بعد. */
  after.forEach((text, i) => {
    if (out[i]) return;
    const id = beforeIds[i];
    if (id && !takenIds.has(id)) {
      out[i] = id;
      takenIds.add(id);
    }
  });

  /* (٣) وما بقي يُولَد. */
  for (let i = 0; i < out.length; i += 1) {
    if (!out[i]) out[i] = newId();
  }
  return out;
}

/**
 * معرّفاتُ جملِ سجلٍّ كما هي **بلا كتابة** (بند ٦).
 *
 * @returns {string[]|null} `null` إن لم تُولَد بعد — وهي حالةٌ عاديّة
 *          لا نقصان: يعمل عندها الرجوعُ إلى النصّ المُطبَّع.
 */
export function idsOf(record) {
  const ids = record?.[SENTENCE_IDS];
  if (!Array.isArray(ids) || !ids.length) return null;
  const texts = sentenceTexts(record.text);
  /*
   * ⚠️ **وطولٌ مختلفٌ يعني معرّفاتٍ متقادمة** — سجلٌّ كُتب نصُّه من
   *    مسارٍ لا يمرّ بـ`updateScript`. فتُقرأ على أنّها غائبة: أن
   *    ترجع إلى النصّ المُطبَّع أأمنُ من أن تنسب مسودّةً لجملةٍ أخرى.
   */
  if (ids.length !== texts.length) return null;
  return ids;
}

/**
 * جملُ سجلٍّ بمعرّفاتها إن وُجدت — للعرض والبحث.
 *
 * @returns {{id: string|null, text: string, index: number}[]}
 *          `index` **عرضٌ لا هُويّة** (بند ٣٧) — رقمُ الجملة على الشاشة.
 */
export function sentencesOf(record) {
  const texts = sentenceTexts(record?.text);
  const ids = idsOf(record);
  return texts.map((text, index) => ({
    id: ids ? ids[index] : null,
    text,
    index,
  }));
}

/**
 * يضمن وجودَ معرّفاتٍ لسجلّ — **ويُنادى عند الكتابة وحدَها**.
 *
 * ⚠️ يعيد المعرّفاتِ ولا يكتب بنفسه: الكتابةُ مسؤوليّةُ من يملك
 *    المعاملة، كي لا تقع كتابتان حيث تكفي واحدة.
 *
 * @returns {{ids: string[], changed: boolean}}
 */
export function ensureIds(record) {
  const texts = sentenceTexts(record?.text);
  const current = idsOf(record);
  if (current) return { ids: current, changed: false };

  const stale = Array.isArray(record?.[SENTENCE_IDS]) ? record[SENTENCE_IDS] : [];
  /*
   * ⚠️ **وحتى الردمُ يوائم** — سجلٌّ فيه معرّفاتٌ بطولٍ مختلف (كُتب
   *    نصُّه من مسارٍ قديم) لا تُرمى معرّفاتُه: تُوائَم بما نعرفه من
   *    النصّ الحاليّ، فينجو ما يمكن أن ينجو.
   */
  const ids = reconcileIds(texts.slice(0, stale.length), stale, texts);
  return { ids, changed: true };
}

/**
 * المعرّفاتُ بعد تعديلِ نصّ — تُنادى من `updateScript` وحدَها.
 *
 * ⚠️ **ولا تُولَد معرّفاتٌ لسجلٍّ لم تكن له** (بند ٦): تعديلُ نصٍّ لا
 *    مسودّةَ له لا يستدعي هُويّةً. فإن لم تكن ثمّة معرّفاتٌ أصلًا
 *    تعود `null` ولا يُكتَب حقل.
 *
 * @returns {string[]|null} معرّفاتٌ جديدةٌ تُكتَب، أو `null` فلا تُمَسّ.
 */
export function idsAfterEdit(record, nextText) {
  const had = Array.isArray(record?.[SENTENCE_IDS]) && record[SENTENCE_IDS].length;
  if (!had) return null;
  const before = sentenceTexts(record.text);
  const after = sentenceTexts(nextText);
  return reconcileIds(before, record[SENTENCE_IDS], after);
}
