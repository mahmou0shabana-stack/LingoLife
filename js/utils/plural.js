/**
 * LingoLife — الجمع في العربيّة
 *
 * كُتب هذا المنطق ثلاث مرّات في ثلاث شاشات قبل أن يُستخرَج، وأخطأ في
 * كل مرّة على نحوٍ مختلف: «٢ ذكرىين» و«١١ حاجات» و«٧ شخص». والثالثة
 * كانت الإشارة.
 *
 * ═══════════════════════════════════════════════════════════════
 * لماذا الصيغ تُمرَّر ولا تُشتقّ
 * ═══════════════════════════════════════════════════════════════
 *
 * لا قاعدةَ اشتقاقٍ عامّة تُغني عن الكتابة الصريحة: «ذكرى» مقصورةٌ
 * تصير «ذكريتان»، و«شخص» يصير «شخصان» و«أشخاص»، و«موقف» يصير
 * «موقفان» و«مواقف». وإلحاقُ «ين» بالمفرد — وهو ما جرّبتُه — يُنتج
 * «ذكرىين».
 *
 * والقاعدة العدديّة نفسها ثابتة:
 *
 *   ١  → مفرد            · «ذكرى»
 *   ٢  → مثنّى           · «ذكريتان»
 *  ٣–١٠ → جمع قلّة        · «ذكريات»
 *  ١١+  → تمييزٌ مفرد     · «١١ ذكرى» لا «١١ ذكريات»
 */

/**
 * الاسم الموافق للعدد — **بلا الرقم**.
 *
 * ⚠️ يعيد الاسم وحده لأن الرقم يُطبَع غالبًا منفصلًا (في `<b>` كبيرة
 *    فوق الاسم مثلًا). ودمجُهما هنا أنتج «١١ ١١ حاجات» في المعاينة.
 *
 * @param {number} n
 * @param {string} one  المفرد — ويصلح للأحد عشر فأكثر أيضًا
 * @param {string} two  المثنّى
 * @param {string} few  جمع القلّة (٣–١٠)
 */
export function plural(n, one, two, few) {
  if (n === 1) return one;
  if (n === 2) return two;
  if (n >= 3 && n <= 10) return few;
  return one;
}

/**
 * العدد واسمه معًا — للسطور التي يُقرأ فيها الاثنان متجاورين.
 *
 * ⚠️ **الواحد والاثنان بلا رقم.** العربيّة تحمل العدد في الصيغة نفسها:
 *    «ذكريتان» لا «٢ ذكريتان»، و«تصحيح» لا «١ تصحيح». وإعادة الرقم
 *    ركاكةٌ تُقرأ فورًا — ظهرت في «وفيه 1 تصحيح تاني» في شاشة التحليل،
 *    وهي رابع مرّة يُخطئ فيها الجمعُ في هذا المشروع.
 *
 * ⚠️ ولا يُلحَق «واحد» بالمفرد هنا: تذكيرُه وتأنيثه يتبعان الاسم
 *    («تصحيحٌ واحد» و«ذكرى واحدة»)، والدالّة لا تعرف جنس ما مُرِّر
 *    إليها. فالمفرد وحده أسلم — ومَن أراد «واحدة» كتبها في نصّه.
 */
export function counted(n, one, two, few) {
  if (n === 1) return one;
  if (n === 2) return two;
  return `${n} ${plural(n, one, two, few)}`;
}
