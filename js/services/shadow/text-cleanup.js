/**
 * LingoLife — تنظيف النصّ المستخرَج قبل التقسيم (WS40 بند 9، WS42 بند 5-9)
 *
 * ═══════════════════════════════════════════════════════════════
 * بلاغُك (WS42)
 * ═══════════════════════════════════════════════════════════════
 *
 * > التنظيفُ القديم يحذف فقط الأسطرَ التي هي أرقامٌ أو رموزٌ زخرفيّة
 * >  بالكامل — وهذا لا يحلّ ضوضاءً **مغروسةً** حول محتوًى حقيقي.
 * >  لا تحذف كلَّ رمز: الروسية تستعمل الفاصلة والنقطة والنقطتين
 * >  والفاصلة المنقوطة والشرطة والأقواس والاقتباس والنسبة المئوية
 * >  والأرقام والتواريخ بمعنًى حقيقيّ. ميّز **اللغة** عن **ضوضاء
 * >  التخطيط/OCR**.
 *
 * ═══════════════════════════════════════════════════════════════
 * خطّ الأنابيب المرحليّ
 * ═══════════════════════════════════════════════════════════════
 *
 *   نصٌّ خامٌّ مستخرَج
 *   → تطبيع يونيكود (NFC)
 *   → تطبيع المسافات (نهايات الأسطر، المسافات الأفقية، الفراغات الزائدة)
 *   → إزالة الأسطر الزخرفية الواضحة (سطرٌ كاملٌ رموزًا/أرقامًا بلا حرف)
 *   → طيّ سلاسل الرموز المكرَّرة (`----`، `====`، `••••`) إلى لا شيء
 *   → إصلاح فراغ OCR الناقص بعد علامة نهاية جملة قبل حرفٍ كبير
 *   → (والباقي — كل ترقيمٍ ورقمٍ منفرد أو مغروس — لا يُمَسّ إطلاقًا)
 *
 * ⚠️ **ولا مرحلة تلمس رمزًا أو رقمًا منفردًا داخل جملةٍ حقيقية.** كل
 *    مرحلةٍ هنا تعمل إمّا على **السطر كاملًا** (فارغٌ من أي حرفٍ لغويّ)
 *    أو على **سلسلة رموزٍ مكرَّرة ٣ فأكثر** (لا يمكن أن تكون هذه علامة
 *    ترقيمٍ حقيقية في الروسية). وحيث الشكّ قائمٌ — رقمٌ منفردٌ، رمزٌ
 *    واحدٌ مغروسٌ بين كلمتين («слово + другое») — لا شيء يُحذَف؛
 *    المراجعةُ اليدوية (لوحة المعاينة، WS42-F) هي الحكم الأخير.
 *
 * ⚠️ **ولا يُكتَب فوق المصدر أبدًا.** `cleanExtractedTextDetailed`
 *    تعيد `raw` (كما استُخرج) و`cleaned` (نسخة الممارسة) منفصلَين —
 *    المستدعي يقرّر أيّهما يحفظ، ولا شيء يُفقَد صامتًا.
 */

/** رموزٌ زخرفيّة/تخطيطية — لا معنى لغويًّا لها منفردةً في الروسية أبدًا. */
const DECORATIVE_CHARS = '\\-*_=~•·.+|^═─━▪●◆║╌╍⁘※';

/**
 * سطرٌ بأكمله من هذه الرموز و/أو أرقامٍ و/أو مسافات — بلا حرفٍ لغويّ
 * (كيريليّ أو لاتينيّ) على الإطلاق. رقمٌ منفردٌ على سطره هو الحالة
 * الكلاسيكية لرقم صفحة، فيُزال هنا وحده — لا حين يكون مغروسًا في سطرٍ
 * فيه كلام (تلك حالةٌ لا تطابق هذا النمط أصلًا لأن السطر فيه حروف).
 */
const NOISE_LINE = new RegExp(`^[${DECORATIVE_CHARS}\\d\\s]+$`);

/** سلسلةُ رمزٍ واحدٍ مكرَّرٍ ٣ مرّاتٍ فأكثر — لا يمكن أن تكون ترقيمًا حقيقيًّا. */
const REPEATED_SYMBOL_RUN = new RegExp(`([${DECORATIVE_CHARS}])\\1{2,}`, 'g');

/** حرفٌ كبيرٌ (كيريليّ أو لاتينيّ) يلي علامة نهاية جملة بلا فراغ — فراغٌ ابتلعه OCR. */
const MISSING_SPACE_AFTER_SENTENCE = /([.!?])([А-ЯЁA-Z])/g;

/**
 * المرحلة الكاملة — تعيد النصّ المنظَّف وحده (الاستعمال الشائع).
 * @param {string} raw
 * @returns {string}
 */
export function cleanExtractedText(raw) {
  return cleanExtractedTextDetailed(raw).cleaned;
}

/**
 * المرحلة الكاملة مع تفاصيل ما تغيَّر — للوحة المعاينة (WS42-F).
 *
 * @param {string} raw
 * @returns {{
 *   raw: string,
 *   cleaned: string,
 *   removedLines: string[],
 *   symbolRunsCollapsed: number,
 *   spacingFixes: number,
 * }}
 */
export function cleanExtractedTextDetailed(rawInput) {
  const raw = String(rawInput || '');

  // ١. تطبيع يونيكود — بعض محرّكات OCR تُخرِج تشكيلًا مُفكَّكًا
  //    (حرفًا + علامةً منفصلة) بدل الشكل المركَّب المعتاد.
  const normalized = raw.normalize('NFC');

  // ٢. تطبيع المسافات: نهايات أسطر موحَّدة، بلا فراغٍ زائدٍ آخر السطر.
  const withNormalizedWhitespace = normalized
    .replace(/\r\n?/g, '\n')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, '').replace(/[ \t]{2,}/g, ' '))
    .join('\n');

  // ٣. إزالة الأسطر الزخرفية الواضحة.
  const removedLines = [];
  const linesAfterNoise = withNormalizedWhitespace.split('\n').filter((line) => {
    const isNoise = line.trim() !== '' && NOISE_LINE.test(line);
    if (isNoise) removedLines.push(line.trim());
    return !isNoise;
  });

  // ٤. طيّ سلاسل الرموز المكرَّرة — أينما وقعت، حتى مغروسةً وسط سطرٍ حقيقيّ.
  let symbolRunsCollapsed = 0;
  const afterSymbolRuns = linesAfterNoise
    .join('\n')
    .replace(REPEATED_SYMBOL_RUN, () => {
      symbolRunsCollapsed++;
      return ' ';
    });

  // ٥. فراغٌ ناقصٌ بعد نهاية جملة قبل حرفٍ كبير — عطبُ تباعدٍ شائعٌ في OCR.
  let spacingFixes = 0;
  const afterSpacing = afterSymbolRuns.replace(MISSING_SPACE_AFTER_SENTENCE, (_, punct, letter) => {
    spacingFixes++;
    return `${punct} ${letter}`;
  });

  const cleaned = afterSpacing
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim();

  return { raw, cleaned, removedLines, symbolRunsCollapsed, spacingFixes };
}
