/** كم ننتظر ظهور العنصر قبل أن نستسلم. */
const TRIES = 20;
const GAP = 60;

/**
 * ينزل إلى عنصرٍ داخل الشاشة ويُضيئه.
 *
 * @param {string} id معرّف الصفّ — مثل `CP_01H…`
 * @returns {Promise<boolean>} هل وُجد؟
 */
export async function revealRow(id) {
  if (!id) return false;

  for (let attempt = 0; attempt < TRIES; attempt++) {
    const node = document.querySelector(`[data-row="${CSS.escape(id)}"]`);
    if (node) {
      node.scrollIntoView({ block: 'center', behavior: 'smooth' });
      node.classList.add('is-revealed');
      setTimeout(() => node.classList.remove('is-revealed'), 2200);
      return true;
    }
    await new Promise((resolve) => setTimeout(resolve, GAP));
  }
  return false;
}

/**
 * يبني رابطًا يفتح شاشةً **وينزل إلى صفٍّ فيها**.
 *
 * ⚠️ `?at=` لا `#`: المسار نفسه يعيش في الـhash، فعلامةُ تجزئةٍ ثانية
 *    لا معنى لها. راجع `router.currentQuery`.
 */
export const rowLink = (path, rowId) => (rowId ? `${path}?at=${encodeURIComponent(rowId)}` : path);
