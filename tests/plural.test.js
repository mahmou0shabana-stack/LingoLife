/**
 * LingoLife — اختبارات الجمع في العربيّة
 *
 * ⚠️ **أربع مرّات أخطأ هذا المنطق قبل أن يُختبَر**: «٢ ذكرىين» و«١١
 *    حاجات» و«٧ شخص» و«وفيه 1 تصحيح تاني». والثلاث الأُوَل استُخرجن
 *    إلى `utils/plural.js` — والرابعة مرّت بعد الاستخراج، لأن الملفّ
 *    خرج بلا اختبارٍ واحد.
 *
 *    فالقاعدة العدديّة كلها محروسةٌ هنا الآن، بأمثلةٍ من الشاشات
 *    الحقيقيّة لا بأرقامٍ مجرّدة.
 */

import { describe, it, expect } from './test-runner.js';
import { plural, counted } from '../js/utils/plural.js';

const ذكرى = ['ذكرى', 'ذكريتين', 'ذكريات'];

describe('الاسم الموافق للعدد', () => {
  it('واحدٌ مفرد، واثنان مثنّى، وثلاثةٌ إلى عشرةٍ جمعُ قلّة', async () => {
    expect(plural(1, ...ذكرى)).toBe('ذكرى');
    expect(plural(2, ...ذكرى)).toBe('ذكريتين');
    expect(plural(3, ...ذكرى)).toBe('ذكريات');
    expect(plural(10, ...ذكرى)).toBe('ذكريات');
  });

  it('⚠️ أحدَ عشرَ فأكثر تمييزٌ مفرد — لا «١١ ذكريات»', async () => {
    expect(plural(11, ...ذكرى)).toBe('ذكرى');
    expect(plural(19, ...ذكرى)).toBe('ذكرى');
    expect(plural(100, ...ذكرى)).toBe('ذكرى');
  });

  it('الصفر يأخذ صيغة الجمع الكثير — «مفيش ذكريات»', async () => {
    expect(plural(0, ...ذكرى)).toBe('ذكرى');
  });

  it('⚠️ ولا يُشتقّ المثنّى بإلحاق «ين» — «ذكرىين» كانت أوّل غلطة', async () => {
    // الصيغة تُمرَّر مكتوبةً، فلا اشتقاق يُفسدها.
    expect(plural(2, 'شخص', 'شخصان', 'أشخاص')).toBe('شخصان');
    expect(plural(2, 'موقف', 'موقفان', 'مواقف')).toBe('موقفان');
  });
});

describe('العدد واسمه معًا', () => {
  it('⚠️ الواحد بلا رقم — «تصحيح» لا «1 تصحيح»', async () => {
    expect(counted(1, 'تصحيح', 'تصحيحين', 'تصحيحات')).toBe('تصحيح');
    expect(counted(1, ...ذكرى)).toBe('ذكرى');
  });

  it('⚠️ والمثنّى بلا رقم — «ذكريتين» لا «٢ ذكريتين»', async () => {
    expect(counted(2, ...ذكرى)).toBe('ذكريتين');
    expect(counted(2, 'ظهور', 'ظهورين', 'ظهورات')).toBe('ظهورين');
  });

  it('وثلاثةٌ فأكثر بالرقم', async () => {
    expect(counted(3, ...ذكرى)).toBe('3 ذكريات');
    expect(counted(10, ...ذكرى)).toBe('10 ذكريات');
    expect(counted(11, ...ذكرى)).toBe('11 ذكرى');
  });

  it('والصفر يُقال كما هو', async () => {
    expect(counted(0, ...ذكرى)).toBe('0 ذكرى');
  });

  it('⚠️ ولا يُلحَق «واحد» بالمفرد — التذكير يتبع الاسم لا الدالّة', async () => {
    // «ذكرى واحد» و«تصحيح واحدة» كلاهما خطأ، والدالّة لا تعرف الجنس.
    expect(counted(1, ...ذكرى).includes('واحد')).toBe(false);
  });
});
